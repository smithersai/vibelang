import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { pathToFileURL } from "node:url"
import { test } from "node:test"
import fc from "fast-check"

test("shipped directive readers load and classify sources without a compiler peer", async t => {
  const root = mkdtempSync(join(tmpdir(), "directive-standalone-"))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const readers = []
  for (const name of ["vite", "unplugin"]) {
    const directory = join(root, name)
    mkdirSync(directory)
    const file = join(directory, "reader.mjs")
    writeFileSync(file, readFileSync(new URL(`../../${name}/src/vibe-directive.js`, import.meta.url)))
    readers.push(await import(pathToFileURL(file).href))
  }
  fc.assert(fc.property(
    fc.constantFrom("ts", "tsx", "mts", "cts", "vibe", "vibex", "d.ts"),
    fc.boolean(),
    fc.constantFrom("", "\uFEFF", "#!/usr/bin/env node\n"),
    (extension, marked, prefix) => {
      const file = join(root, "main." + extension)
      const text = prefix + (marked ? "// @vibe\n" : "// @vibe is an ordinary comment\n") + "export const value = 1\n"
      writeFileSync(file, text)
      const directive = marked && ["ts", "tsx", "mts", "cts"].includes(extension)
      for (const reader of readers) {
        assert.equal(reader.hasVibeDirective(file, text), directive)
        assert.equal(reader.fileHasVibeDirective(file), directive)
        assert.equal(reader.isVibeLangFile(file), ["vibe", "vibex"].includes(extension) || directive)
      }
    }
  ), { numRuns: 120, seed: 421932 })
})

test("generated plugin readers retain the complete canonical directive implementation", () => {
  const header = "// Generated by packages/compiler/generate-directive-readers.mjs from packages/compiler/vibe-directive.mjs. Do not edit.\n"
  const source = readFileSync(new URL("../vibe-directive.mjs", import.meta.url), "utf8")
  for (const name of ["vite", "unplugin"]) {
    assert.equal(readFileSync(new URL(`../../${name}/src/vibe-directive.js`, import.meta.url), "utf8"), header + source)
  }
})

test("directive generation detects stale readers and regenerates both packages", t => {
  const root = mkdtempSync(join(tmpdir(), "directive-generation-"))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  mkdirSync(join(root, "compiler"))
  for (const name of ["vite", "unplugin"]) mkdirSync(join(root, name, "src"), { recursive: true })
  const generator = join(root, "compiler", "generate-directive-readers.mjs")
  const canonical = join(root, "compiler", "vibe-directive.mjs")
  writeFileSync(generator, readFileSync(new URL("../generate-directive-readers.mjs", import.meta.url)))
  writeFileSync(canonical, readFileSync(new URL("../vibe-directive.mjs", import.meta.url)))
  const run = mode => spawnSync(process.execPath, [generator, mode], { encoding: "utf8" })
  assert.equal(run("--write").status, 0)
  assert.equal(run("--check").status, 0)
  writeFileSync(canonical, readFileSync(canonical, "utf8") + "\n// Additional canonical source.\n")
  const stale = run("--check")
  assert.notEqual(stale.status, 0)
  assert.match(stale.stderr, /is stale/)
  assert.equal(run("--write").status, 0)
  assert.equal(run("--check").status, 0)
  for (const name of ["vite", "unplugin"]) {
    assert.match(readFileSync(join(root, name, "src", "vibe-directive.js"), "utf8"), /Additional canonical source/)
  }
})
