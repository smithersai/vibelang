// opencode-32: a migrated package's `default` export names its emitted
// JavaScript, which the `bun build` CLI and plain Node read; the loaders run
// the .vibe source instead (emitted-js.mjs).
import { strict as assert } from "node:assert"
import { spawnSync } from "node:child_process"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { test } from "node:test"
import { fileURLToPath } from "node:url"
import fc from "fast-check"
import { reexportOf, sourceOfEmitted } from "../emitted-js.mjs"

const repo = fileURLToPath(new URL("../../../", import.meta.url))
const compilerPackage = fileURLToPath(new URL("../", import.meta.url))
const native = process.env.VIBELANG_BINARY || join(repo, "typescript/built/local/tsc")
const effect = join(process.env.EFFECT_NODE_MODULES || join(repo, "experiments/node_modules"), "effect")
const runtime = join(repo, "packages/runtime")
const hasBun = spawnSync("bun", ["--version"]).status === 0
const missing = [native, effect, join(runtime, "dist/index.js")].find((path) => !existsSync(path))
const skip = missing !== undefined && `run typescript/vibelang/smoke.sh first; missing ${missing}`

function write(root, files) {
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), text)
  }
}

// opencode's shape, minimized: packages/schema's skill.vibe, its committed
// emit, and an app that imports @demo/schema/skill through the workspace link.
function workspace(t) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "vibelang-emitted-js-")))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const schema = {
    name: "@demo/schema", type: "module",
    exports: { "./skill": { types: "./src/skill.d.vibe.ts", "vibelang-source": "./src/skill.vibe", default: "./.vibelang/js/src/skill.js" } }
  }
  write(root, {
    "package.json": JSON.stringify({ name: "demo", private: true, type: "module", workspaces: ["packages/*"] }),
    "packages/schema/package.json": JSON.stringify(schema),
    "packages/schema/tsconfig.json": JSON.stringify({ compilerOptions: { target: "ES2022", module: "NodeNext", moduleResolution: "NodeNext", strict: true, types: [], noEmit: true }, include: ["src/**/*"] }),
    "packages/schema/src/skill.vibe": 'export const Skill: string = "from-vibe-source"\nexport const id: object = {}\n',
    "packages/schema/.vibelang/js/src/skill.js": '// Generated by vibelang from src/skill.vibe.\nexport const Skill = "from-emitted-js"\n',
    "packages/app/package.json": JSON.stringify({ name: "app", type: "module" }),
    "packages/app/main.mjs": 'import { Skill } from "@demo/schema/skill"\nconsole.log(Skill)\n',
    "packages/app/main.cjs": 'console.log(require("@demo/schema/skill").Skill)\n',
    "packages/app/same.mjs": 'import { id } from "@demo/schema/skill"\nimport { id as relative } from "../schema/src/skill.vibe"\nconsole.log(id === relative)\n',
    // opencode-46: protocol's script, a .ts file, reads one schema module by
    // its package export and by its path; m5 lost this carry and had two.
    "packages/app/same.ts": `import { id } from "@demo/schema/skill"\nimport { id as absolute } from "${join(root, "packages/schema/src/skill.vibe")}"\nconsole.log(id === absolute, require.resolve("@demo/schema/skill").includes(".vibelang/js"))\n`
  })
  mkdirSync(join(root, "node_modules/@demo"), { recursive: true })
  symlinkSync(join(root, "packages/schema"), join(root, "node_modules/@demo/schema"))
  symlinkSync(realpathSync(effect), join(root, "node_modules/effect"))
  symlinkSync(runtime, join(root, "node_modules/vibelang-runtime"))
  symlinkSync(compilerPackage, join(root, "node_modules/vibelang"))
  const env = { ...process.env, VIBELANG_BINARY: native, VIBELANG_PROJECT: "", VIBELANG_CACHE_DIR: join(root, ".cache") }
  const run = (command, args) => {
    const result = spawnSync(command, args, { cwd: join(root, "packages/app"), encoding: "utf8", env })
    return { status: result.status, out: result.stdout.trim(), err: result.stderr }
  }
  return { root, run }
}

test("sourceOfEmitted maps a package's emitted file to its source, and nothing else", (t) => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "vibelang-emitted-js-")))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  write(root, { "p/src/a.vibe": "", "p/.vibelang/js/src/a.js": "", "p/.vibelang/js/src/b.js": "", "p/src/b.ts": "", "p/src/c.js": "" })
  assert.equal(sourceOfEmitted(join(root, "p/.vibelang/js/src/a.js")), join(root, "p/src/a.vibe"))
  assert.equal(sourceOfEmitted(join(root, "p/.vibelang/js/src/b.js")), join(root, "p/src/b.ts"))
  assert.equal(sourceOfEmitted(join(root, "p/src/c.js")), undefined)
  assert.equal(sourceOfEmitted(join(root, "p/.vibelang/js/src/a.mjs")), undefined)
  assert.equal(sourceOfEmitted(undefined), undefined)
})

// Generated layouts: nested directories, dotted names, a .vibelang/js inside
// another, and sources that are present or missing.
const segment = fc.constantFrom("src", "lib", "a.b", "x-y", "deep", ".vibelang")
test("emitted-source: an emitted .js file maps to the .vibe beside its package's mirror path, only when that exists", () => {
  fc.assert(fc.property(fc.array(segment, { maxLength: 3 }), fc.array(segment, { maxLength: 3 }), fc.constantFrom("skill", "index", "a.b"), fc.boolean(), (pkg, rel, file, present) => {
    const root = realpathSync(mkdtempSync(join(tmpdir(), "vibelang-emitted-js-")))
    try {
      const packageDir = join(root, ...pkg)
      const emitted = join(packageDir, ".vibelang", "js", ...rel, file + ".js")
      const source = join(packageDir, ...rel, file + ".vibe")
      write(root, { [emitted.slice(root.length + 1)]: "", ...(present ? { [source.slice(root.length + 1)]: "" } : {}) })
      assert.equal(sourceOfEmitted(emitted), present ? source : undefined)
      assert.equal(sourceOfEmitted(source), undefined)
      assert.equal(sourceOfEmitted(emitted.slice(0, -3) + ".mjs"), undefined)
    } finally {
      rmSync(root, { recursive: true, force: true })
    }
  }), { seed: 35035, numRuns: 200 })
})

test("reexportOf names the source once per form, and exports default only for a source that has one", () => {
  assert.equal(reexportOf("/r/src/a.vibe", true), 'export * from "/r/src/a.vibe"\nimport * as source from "/r/src/a.vibe"\nexport default source.default\n')
  assert.equal(reexportOf("/r/src/a.vibe", false), 'export * from "/r/src/a.vibe"\n')
})

test("node reads a migrated package's emitted JavaScript, and node --import vibelang/register its .vibe source", { skip }, (t) => {
  const { run } = workspace(t)
  assert.deepEqual([run(process.execPath, ["main.mjs"]).out], ["from-emitted-js"])
  const registered = run(process.execPath, ["--import", "vibelang/register", "main.mjs"])
  assert.equal(registered.out, "from-vibe-source", registered.err)
  const same = run(process.execPath, ["--import", "vibelang/register", "same.mjs"])
  assert.equal(same.out, "true", same.err)
})

test("bun build reads the emitted JavaScript, and the vibelang/bun preload runs the .vibe source for import and require", { skip: skip || (!hasBun && "bun is not on PATH") }, (t) => {
  const { root, run } = workspace(t)
  assert.equal(run("bun", ["main.mjs"]).out, "from-emitted-js")
  const imported = run("bun", ["--preload", "vibelang/bun", "main.mjs"])
  assert.equal(imported.out, "from-vibe-source", imported.err)
  const required = run("bun", ["--preload", "vibelang/bun", "main.cjs"])
  assert.equal(required.out, "from-vibe-source", required.err)
  const same = run("bun", ["--preload", "vibelang/bun", "same.mjs"])
  assert.equal(same.out, "true", same.err)
  const script = run("bun", ["run", "--preload", "vibelang/bun", "same.ts"])
  assert.equal(script.out, "true true", script.err)
  const built = run("bun", ["build", "main.mjs", "--target=bun", "--packages=bundle", `--outdir=${join(root, "out")}`])
  assert.equal(built.status, 0, built.err)
  const bundle = readFileSync(join(root, "out/main.js"), "utf8")
  assert.match(bundle, /from-emitted-js/)
  assert.doesNotMatch(bundle, /from-vibe-source/)
})

test("native emitted-source: loader identity follows the native source extension", () => {
  fc.assert(fc.property(
    fc.constantFrom(["ts", "js"], ["tsx", "jsx"], ["mts", "mjs"], ["cts", "cjs"], ["js", "js"]),
    fc.constantFrom("token", "a..b", "ünicode"), fc.boolean(), (extensions, name, present) => {
      const root = realpathSync(mkdtempSync(join(tmpdir(), "opencode-native-emitted-")))
      try {
        const [sourceExtension, emittedExtension] = extensions
        const emitted = join(root, "pkg/.vibelang/js/src", name + "." + emittedExtension)
        const source = join(root, "pkg/src", name + "." + sourceExtension)
        write(root, { [emitted.slice(root.length + 1)]: "", ...(present ? { [source.slice(root.length + 1)]: "" } : {}) })
        assert.equal(sourceOfEmitted(emitted), present ? source : undefined)
      } finally { rmSync(root, { recursive: true, force: true }) }
    }), { numRuns: 100 })
})
