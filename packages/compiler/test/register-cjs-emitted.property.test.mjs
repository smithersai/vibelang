// Smithers registry's CJS artifact imports a migrated dependency by its
// committed .vibelang/js export. Native TypeScript twins exercise Node's real
// synchronous resolver without a compiler stub; emitted-js.test covers .vibe.
import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { test } from "node:test"
import { fileURLToPath, pathToFileURL } from "node:url"
import fc from "fast-check"

const corpus = JSON.parse(readFileSync(new URL("./corpus/smithers-registry-cjs-emitted-export.json", import.meta.url), "utf8"))
const register = fileURLToPath(new URL("../register.mjs", import.meta.url))
function witness({ name = "leaf", extension = "ts", consumer = "require", present = true }) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "smithers-cjs-emitted-")))
  const write = (p, text) => { const path = join(root, p); mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text) }
  try {
    const out = extension === "cts" ? "cjs" : extension === "mts" ? "mjs" : "js"
    const source = "pkg/src/" + name + "." + extension
    const emitted = "pkg/.vibelang/js/src/" + name + "." + out
    write("pkg/package.json", JSON.stringify({ name: "@demo/registry", type: "module", exports: { "./leaf": "./" + emitted.slice(4).split("/").map(encodeURIComponent).join("/") } }))
    if (present) write(source, extension === "cts"
      ? 'module.exports = { text: "source", token: {} }\n'
      : 'export const text: string = "source"\nexport const token: object = {}\n')
    write(emitted, "// Generated by vibelang from src/" + name + "." + extension + ".\n" +
      (extension === "cts" ? 'module.exports = { text: "emitted", token: {} }\n' : 'export const text = "emitted"\nexport const token = {}\n'))
    mkdirSync(join(root, "node_modules/@demo"), { recursive: true })
    symlinkSync(join(root, "pkg"), join(root, "node_modules/@demo/registry"))
    const direct = present ? join(root, source) : join(root, emitted)
    const entry = consumer === "import" ? "entry.mjs" : "entry.cjs"
    const check = 'const a = left.default ?? left, b = right.default ?? right; console.log(JSON.stringify({text:a.text,same:a.token===b.token}))\n'
    write(entry, consumer === "import"
      ? 'import * as left from "@demo/registry/leaf"; import * as right from ' + JSON.stringify(pathToFileURL(direct).href) + ';\n' + check
      : 'const left = require("@demo/registry/leaf"), right = require(' + JSON.stringify(direct) + ')\n' + check)
    if (consumer === "createRequire") write(entry,
      'const load = require("node:module").createRequire(__filename)\nconst left=load("@demo/registry/leaf"),right=load(' + JSON.stringify(direct) + ')\n' + check)
    const r = spawnSync(process.execPath, ["--import", register, entry], {
      cwd: root, encoding: "utf8", timeout: 10000,
      env: { ...process.env, VIBELANG_PROJECT: "", VIBELANG_CACHE_DIR: join(root, ".cache") }
    })
    assert.equal(r.status, 0, r.stderr)
    assert.deepEqual(JSON.parse(r.stdout), { text: present ? "source" : "emitted", same: true })
  } finally { rmSync(root, { recursive: true, force: true }) }
}
test("Smithers CJS artifact requires a dependency through its emitted export with source identity", () => witness(corpus.case))
test("Smithers CJS artifact createRequire preserves the same source identity", () => witness({ consumer: "createRequire" }))
test("emitted-source resolution agrees with the native TypeScript twin across source names and consumers", () => {
  fc.assert(fc.property(
    fc.record({
      name: fc.constantFrom("leaf", "with space", "hash#name", "percent%name", "unicode-é", "plus+name", "[leaf]", "$leaf"),
      extension: fc.constantFrom("ts", "mts", "cts"),
      consumer: fc.constantFrom("require", "createRequire", "import"),
      present: fc.boolean()
    }),
    witness
  ), { seed: 20261104, numRuns: 48 })
})
