import { readFileSync, writeFileSync } from "node:fs"

const mode = process.argv[2]
if (!["--write", "--check"].includes(mode) || process.argv.length !== 3) {
  throw new Error("usage: node packages/compiler/generate-directive-readers.mjs --write|--check")
}
const header = "// Generated by packages/compiler/generate-directive-readers.mjs from packages/compiler/vibe-directive.mjs. Do not edit.\n"
const source = header + readFileSync(new URL("./vibe-directive.mjs", import.meta.url), "utf8")
for (const name of ["vite", "unplugin"]) {
  const file = new URL(`../${name}/src/vibe-directive.js`, import.meta.url)
  if (mode === "--write") writeFileSync(file, source)
  else if (readFileSync(file, "utf8") !== source) {
    throw new Error(`packages/${name}/src/vibe-directive.js is stale; run node packages/compiler/generate-directive-readers.mjs --write`)
  }
}
