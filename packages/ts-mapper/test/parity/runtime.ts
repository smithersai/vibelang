// The runtime column of the parity harness: does the mapper's JavaScript
// behave as the fork's? For each runnable case, a case with a
// `// expect-result: <json>` line, every .vibe source compiles with the
// mapper's Emit (vibelang-mapper --emit), the case's .ts sources compile with
// stock tsc (types erased, no check), and the entry runs as
// typescript/vibelang/harness.mjs runs it: out/run.mjs imports main(), runs
// it, and prints `@@result <json>`. The case passes when that line is the
// expected JSON, the same comparison the fork's own suite makes. The standalone
// CLI exits nonzero if any selected case fails, including harness failures.
//
// The JavaScript runs against vibelang-runtime as built for the fork, through
// runtime-shim.mjs, which adds the run-time exports the executable
// rendering calls that the runtime does not have yet ($isRun, $direct,
// $fast). The shim lives in this test only.
//
//   parity.ts calls runtimeParity for the runtime column of summary.md.
//   bun runtime.ts [case...]   the runtime column alone, with the PARITY_*
//                              variables run.sh sets; prints one line per case
import { mapperEntry } from "./mapper-options"
import { parseJsonc } from "../../../compiler/cache.mjs"
import { exec } from "./command"
import fs from "node:fs"
import os from "node:os"
import path from "node:path"

export type RuntimeCase = { id: string; dir: string }
export type RuntimeResult = {
  ok: boolean
  // detail: why the case failed, or "" when it passed.
  detail: string
  expected: string
  actual: string | null
  // emit: the mapper's diagnostics while compiling the case's .vibe files.
  emit: { files: number; diagnostics: number; codes: Record<string, number> }
  ms: number
}
export type RuntimeOptions = {
  outDir: string // the harness's out directory; this column works under out/work/runtime and out/nm/runtime
  mapper: string // the vibelang-mapper binary
  stockTsc: string
  effectDir: string
  runtimeDir: string // vibelang-runtime, built
  jobs: number
}

const here = import.meta.dir
const resultMarker = "@@result "
const skipDirs = new Set(["node_modules", "out", "dist", ".cache", "expected"])
const sourcePattern = /\.(vibe|ts|mts|cts|tsx)$/

// Use the same filename mapping for locating the entry and checking emit output.
function emittedPath(source: string): string {
  return source.replace(/\.(vibe|ts|tsx)$/, ".js").replace(/\.mts$/, ".mjs").replace(/\.cts$/, ".cjs")
}

function walk(dir: string): string[] {
  const files: string[] = []
  const visit = (rel: string) => {
    for (const entry of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const child = rel ? `${rel}/${entry.name}` : entry.name
      if (entry.isDirectory()) {
        if (!skipDirs.has(entry.name)) visit(child)
      } else if (entry.isFile()) files.push(child)
    }
  }
  visit("")
  return files
}

async function pool<T>(items: T[], size: number, fn: (item: T) => Promise<void>) {
  let next = 0
  await Promise.all(Array.from({ length: Math.min(size, items.length) }, async () => {
    while (next < items.length) await fn(items[next++])
  }))
}

// expectedResult returns the case's expected result and the entry module
// that holds it, as harness.mjs's readHeaders finds them: the first
// top-level source, in name order, with an expect-result line.
export function expectedResult(dir: string): { result: string; entry: string } | undefined {
  for (const name of fs.readdirSync(dir).sort()) {
    if (!/\.(vibe|ts|mts|cts)$/.test(name) || name.endsWith(".d.ts")) continue
    const line = fs.readFileSync(path.join(dir, name), "utf8").split("\n").find((l) => l.startsWith("// expect-result:"))
    if (line) return { result: JSON.stringify(JSON.parse(line.slice("// expect-result:".length))), entry: emittedPath(name) }
  }
  return undefined
}

// Run the case as harness.mjs does, quoting the entry as a literal URL path.
function runner(entry: string): string {
  return `// Generated by vibelang/harness.mjs: runs main() and prints its result.
import { Cause, Effect, Exit } from "effect"
import { main } from ${JSON.stringify("./" + entry.split("/").map(encodeURIComponent).join("/"))}

const timeout = new Promise((resolve) => setTimeout(resolve, 10_000, "timeout"))
const exit = await Promise.race([Effect.runPromiseExit(main()), timeout])
if (exit === "timeout") console.log("${resultMarker}timed out after 10 s")
else if (Exit.isSuccess(exit)) console.log("${resultMarker}" + JSON.stringify(exit.value))
else {
  console.log("${resultMarker}failed: " + Cause.pretty(exit.cause).split("\\n")[0])
  console.error(Cause.pretty(exit.cause))
}
process.exit(0)
`
}

// setupModules makes the node_modules every case copy links to: effect,
// the shim as vibelang-runtime, and the built runtime as vibelang-runtime-real.
// The shim is a real directory, so its own imports resolve beside it.
function setupModules(o: RuntimeOptions): string {
  const nm = path.join(o.outDir, "nm", "runtime", "node_modules")
  fs.rmSync(nm, { recursive: true, force: true })
  fs.mkdirSync(nm, { recursive: true })
  fs.symlinkSync(o.effectDir, path.join(nm, "effect"))
  fs.symlinkSync(o.runtimeDir, path.join(nm, "vibelang-runtime-real"))
  const shim = path.join(nm, "vibelang-runtime")
  fs.mkdirSync(shim)
  fs.copyFileSync(path.join(here, "runtime-shim.mjs"), path.join(shim, "index.js"))
  fs.writeFileSync(path.join(shim, "kernel.js"), `export * from "vibelang-runtime-real/kernel"\n`)
  fs.writeFileSync(path.join(shim, "data-methods.js"), `export { $method } from "vibelang-runtime-real/data-methods"\n`)
  fs.writeFileSync(path.join(shim, "package.json"), `${JSON.stringify({ name: "vibelang-runtime", type: "module", exports: { ".": "./index.js", "./kernel": "./kernel.js", "./data-methods": "./data-methods.js" } }, null, 2)}\n`)
  return nm
}

// runCase compiles and runs one case in its copy under out/work/runtime,
// which keeps the case's directory name: a service key names it.
async function runCase(c: RuntimeCase, o: RuntimeOptions, nm: string): Promise<RuntimeResult> {
  const t0 = performance.now()
  const header = expectedResult(c.dir)
  const result: RuntimeResult = { ok: false, detail: "", expected: header?.result ?? "", actual: null, emit: { files: 0, diagnostics: 0, codes: {} }, ms: 0 }
  const done = (detail: string) => ({ ...result, detail, ms: Math.round(performance.now() - t0) })
  if (!header) return done("no expect-result line")
  const dir = path.join(o.outDir, "work", "runtime", c.id)
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(path.dirname(dir), { recursive: true })
  fs.cpSync(c.dir, dir, { recursive: true, filter: (src) => !["node_modules", "out", "dist", ".cache"].includes(path.relative(c.dir, src).split(path.sep)[0]) })
  fs.symlinkSync(nm, path.join(dir, "node_modules"))
  const tsconfig = parseJsonc(fs.readFileSync(path.join(dir, "tsconfig.json"), "utf8"))
  const options = tsconfig.compilerOptions ?? {}
  const outDir = path.resolve(dir, options.outDir ?? "out")
  const sources = walk(dir).filter((f) => sourcePattern.test(f) && !/\.d\.(vibe\.)?[mc]?ts$/.test(f))
  // tsc's layout: outputs mirror the sources' common directory (every
  // runnable case keeps its sources at the top level).
  const common = options.rootDir ? path.relative(dir, path.resolve(dir, options.rootDir)) : commonDirectory(sources)
  const outputOf = (rel: string) => emittedPath(path.join(outDir, path.relative(common, rel)))

  for (const rel of sources.filter((f) => f.endsWith(".vibe"))) {
    const argv = [o.mapper, "--emit", path.join(dir, rel), "--out", outputOf(rel)]
    const emitted = await exec(argv, dir, 60_000)
    result.emit.files++
    for (const m of emitted.stderr.matchAll(/error (EK\d+):/g)) {
      result.emit.diagnostics++
      result.emit.codes[m[1]] = (result.emit.codes[m[1]] ?? 0) + 1
    }
    if (emitted.code !== 0) return done(`vibelang-mapper --emit ${rel} exited ${emitted.code}: ${emitted.stderr.split("\n")[0]}`)
  }
  const tsFiles = sources.filter((f) => !f.endsWith(".vibe"))
  if (tsFiles.length > 0) {
    // The .ts sources only lose their types: they import the .vibe
    // modules, which stock tsc cannot resolve without the mapper.
    const { vibelang: _, ...stockOptions } = options
    const config = { compilerOptions: { ...stockOptions, noCheck: true, noEmit: false, noEmitOnError: false, declaration: false, outDir, rootDir: path.resolve(dir, common || ".") }, files: tsFiles }
    fs.writeFileSync(path.join(dir, "tsconfig.runtime.json"), `${JSON.stringify(config, null, 2)}\n`)
    const compiled = await exec([o.stockTsc, "-p", "tsconfig.runtime.json", "--pretty", "false"], dir, 120_000)
    if (compiled.code !== 0) return done((`stock tsc exited ${compiled.code}: ${(compiled.stdout + compiled.stderr).trim().split("\n")[0]}`).slice(0, 300))
    if (tsFiles.some((f) => !fs.existsSync(outputOf(f)))) return done(`stock tsc wrote no JavaScript for the .ts sources: ${(compiled.stdout + compiled.stderr).split("\n")[0]}`)
  }

  fs.mkdirSync(outDir, { recursive: true })
  // Compiler output may itself contain run.mjs. Keep the runner in an
  // owned directory so no emitted module is overwritten.
  const runnerDir = fs.mkdtempSync(path.join(outDir, ".parity-run-"))
  const entry = path.join(runnerDir, "run.mjs")
  fs.writeFileSync(entry, runner("../" + header.entry))
  const ran = await exec(["node", entry], dir, 60_000)
  result.actual = ran.stdout.split("\n").findLast((line) => line.startsWith(resultMarker))?.slice(resultMarker.length) ?? null
  // Keep the result for diagnosis, and require the process to finish successfully.
  if (ran.code !== 0) return done(`runtime failed (exit: ${ran.code}): ${ran.stderr.trim().split("\n")[0] ?? ""}`.slice(0, 300))
  if (result.actual === header.result) return { ...done(""), ok: true }
  const why = result.actual ?? `printed no result (exit ${ran.code}): ${ran.stderr.trim().split("\n").find((l) => /Error|error/.test(l)) ?? ran.stderr.trim().split("\n")[0] ?? ""}`
  return done(why.slice(0, 300))
}

function commonDirectory(files: string[]): string {
  const dirs = files.map((f) => path.dirname(f).split("/").filter((p) => p !== "."))
  if (dirs.length === 0) return ""
  let common = dirs[0]
  for (const d of dirs.slice(1)) {
    let i = 0
    while (i < common.length && i < d.length && common[i] === d[i]) i++
    common = common.slice(0, i)
  }
  return common.join("/")
}

// runtimeParity runs every case and returns each one's result, by id.
export async function runtimeParity(cases: RuntimeCase[], o: RuntimeOptions, progress?: (done: number) => void): Promise<Map<string, RuntimeResult>> {
  const nm = setupModules(o)
  const results = new Map<string, RuntimeResult>()
  let done = 0
  await pool(cases, o.jobs, async (c) => {
    let r: RuntimeResult
    try {
      r = await runCase(c, o, nm)
    } catch (e: any) {
      r = { ok: false, detail: `harness error: ${e?.message ?? e}`, expected: "", actual: null, emit: { files: 0, diagnostics: 0, codes: {} }, ms: 0 }
    }
    results.set(c.id, r)
    progress?.(++done)
  })
  return results
}

// runnableCases returns the cases under typescript/vibelang/cases with an
// expect-result line.
export function runnableCases(root: string): RuntimeCase[] {
  const casesDir = path.join(root, "typescript", "vibelang", "cases")
  return fs
    .readdirSync(casesDir)
    .sort()
    .filter((name) => fs.existsSync(path.join(casesDir, name, "tsconfig.json")) && expectedResult(path.join(casesDir, name)) !== undefined)
    .map((name) => ({ id: name, dir: path.join(casesDir, name) }))
}

if (import.meta.main) {
  const env = (name: string) => {
    const value = process.env[name]
    if (!value) {
      console.error(`runtime.ts: ${name} is not set; run packages/ts-mapper/test/parity/run.sh, or set the PARITY_* variables it sets`)
      process.exit(2)
    }
    return value
  }
  const root = env("PARITY_ROOT")
  const selectors = process.argv.slice(2).filter((a) => !a.startsWith("--"))
  let cases = runnableCases(root)
  if (selectors.length > 0) cases = cases.filter((c) => selectors.some((s) => c.id === s || c.id.includes(s)))
  const o: RuntimeOptions = {
    outDir: process.env.PARITY_OUT ?? path.join(here, "out"),
    mapper: env("PARITY_MAPPER"),
    stockTsc: env("PARITY_STOCK_TSC"),
    effectDir: env("PARITY_EFFECT_DIR"),
    runtimeDir: env("PARITY_RUNTIME_DIR"),
    jobs: Math.max(2, Math.min(12, os.availableParallelism() >> 1)),
  }
  const results = await runtimeParity(cases, o)
  let passed = 0
  for (const c of cases) {
    const r = results.get(c.id)!
    if (r.ok) passed++
    console.log(`${r.ok ? "ok  " : "FAIL"} ${c.id}${r.ok ? "" : `: ${r.detail}`}${r.emit.diagnostics ? ` [emit: ${Object.entries(r.emit.codes).map(([k, n]) => `${k} ${n}`).join(", ")}]` : ""}`)
  }
  console.log(`runtime parity: ${passed}/${cases.length}`)
  if (passed !== cases.length) process.exitCode = 1
}
