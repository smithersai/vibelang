// Source-extension renames also reach authored declaration imports. Compiler
// output remains generated from its source rather than edited by the codemod.
import { existsSync, readFileSync } from "node:fs"
import { isAbsolute, join, posix, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { loadTypeScript } from "./declarations.mjs"
import { isDeclarationFile } from "./util.mjs"

const importer = /\.(?:[cm]?[jt]sx?|vibex?)$/
const generatedDirectory = /(?:^|\/)(?:node_modules|dist|build|coverage|vendor|vendored|third_party|\.git|\.jj|\.cache|\.turbo|\.vite|\.vibelang|\.vibe)(?:\/|$)/
const compatibilityDeclaration = /(?:\.d\.vibex?\.ts|\.vibex?\.[^/]+\.d\.ts)$/
const generatedHeader = /(?:@generated\b|(?:Code generated|Generated by)[^\r\n]*|DO NOT EDIT)/i
const within = (directory, file) => {
  const path = relative(directory, file).replaceAll(String.fromCharCode(92), "/")
  return path === "" || path !== ".." && !path.startsWith("../") && !isAbsolute(path)
}

/** Tracked source importers, including authored declarations but no emit outputs. */
export function importerPaths(root, tracked) {
  const files = new Set(tracked), configs = new Map()
  let ts
  const outputs = file => {
    for (let directory = posix.dirname(file); ; directory = posix.dirname(directory)) {
      const config = ["vibe.config.json", "tsconfig.json", "jsconfig.json"]
        .map(name => join(root, directory, name)).find(existsSync)
      if (config) {
        if (!configs.has(config)) {
          ts ??= loadTypeScript([root, fileURLToPath(new URL("../../../../packages/runtime/", import.meta.url))])
          const parsed = ts.getParsedCommandLineOfConfigFile(resolve(config), {}, {
            ...ts.sys, onUnRecoverableConfigFileDiagnostic(diagnostic) {
              throw new Error("Cannot classify declaration imports: " + ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"))
            }
          })
          configs.set(config, [parsed?.options.outDir, parsed?.options.declarationDir].filter(Boolean))
        }
        return configs.get(config)
      }
      if (directory === ".") return []
    }
  }
  return tracked.filter(file => {
    if (!importer.test(file)) return false
    if (!isDeclarationFile(file)) return true
    if (generatedDirectory.test(file) || compatibilityDeclaration.test(file)) return false
    const stem = file.replace(/\.d\.[cm]?ts$/, "")
    if (stem !== file && [".ts", ".tsx", ".mts", ".cts", ".vibe", ".vibex", ".js", ".jsx", ".mjs", ".cjs"].some(ext => files.has(stem + ext))) return false
    // Generated markers belong to the leading comment, not a later type string.
    const text = readFileSync(join(root, file), "utf8")
    const header = /^\s*(?:(?:\/\/[^\n]*(?:\n|$)|\/\*[\s\S]*?\*\/)\s*)+/.exec(text)?.[0] ?? ""
    if (generatedHeader.test(header)) return false
    return !outputs(file).some(directory => within(directory, resolve(root, file)))
  })
}
