import { fileURLToPath, pathToFileURL } from "node:url"
import { dirname, join, relative } from "node:path"
import { test } from "node:test"
import { emitPackageJs, writeLoaderRecords } from "../lib/declarations.mjs"
import { loaderRecord } from "../../../../packages/compiler/cache.mjs"
import { renameBatch, rewriteExports } from "../lib/codemod.mjs"

const require = createRequire(new URL("../../../../packages/runtime/package.json", import.meta.url))
const fc = require("fast-check")
const compiler = process.env.VIBELANG_BINARY
const hasBun = spawnSync("bun", ["--version"]).status === 0
const quote = "names the source under the `vibelang-source` condition and the emitted JavaScript under `.vibelang/js/` by `default`"

function write(root, files) {
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, file)), { recursive: true })
    writeFileSync(join(root, file), text)
  }
}
function tree(root, skip = []) {
  const files = {}
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name)
      if (skip.some((s) => path === join(root, s))) continue
      if (entry.isDirectory()) walk(path)
      else files[relative(root, path)] = readFileSync(path, "utf8")
    }
  }
  walk(root)
  return files
}

// A stand-in compiler: writes each listed output (relative to --outDir, or a
// repository path for one outside it) with "export {}" and lists it.
function fakeCompiler(root, outputs) {
  const bin = join(root, ".bin/vibelang")
  mkdirSync(dirname(bin), { recursive: true })
  const lines = outputs.map(({ path, outside }) => outside
    ? `mkdir -p '${dirname(join(root, path))}' && printf 'export {}\\n' > '${join(root, path)}' && echo "TSFILE: ${join(root, path)}"`
    : `mkdir -p "$out/${dirname(path)}" && printf 'export {}\\n' > "$out/${path}" && echo "TSFILE: $out/${path}"`)
  writeFileSync(bin, `#!/bin/sh\nwhile [ $# -gt 0 ]; do [ "$1" = "--outDir" ] && out="$2"; shift; done\n${lines.join("\n")}\nexit 0\n`)
  chmodSync(bin, 0o755)
  return bin
}

test("emitPackageJs keeps each module's JavaScript under .vibelang/js with its source named, and nothing else", async () => {
  const root = mkdtempSync(join(tmpdir(), "migrate-emitted-js-"))
  try {
    write(root, {
      "packages/schema/package.json": "{}", "packages/schema/tsconfig.json": "{}",
      "packages/schema/src/skill.vibe": "", "packages/schema/src/util.ts": "", "packages/schema/test/skill.test.ts": "",
      "packages/stories/config.js": "// tracked\n", "packages/stories/config.d.vibe.ts": "// sidecar\n"
    })
    const before = tree(root)
    const bin = fakeCompiler(root, [
      { path: "src/skill.js" }, { path: "src/util.js" }, { path: "test/skill.test.js" }, { path: "src/orphan.js" },
      { path: "packages/stories/config.js", outside: true }, { path: "packages/stories/new.js", outside: true },
      { path: "packages/stories/config.d.vibe.ts", outside: true }
    ])
    const packageDir = join(root, "packages/schema")
    const result = await emitPackageJs({ compiler: bin, tsconfigs: ["tsconfig.json"], packageDir, root })
    assert.equal(result.files, 2)
    const out = tree(join(packageDir, ".vibelang/js"))
    assert.deepEqual(Object.keys(out).sort(), ["src/skill.js", "src/util.js"])
    assert.equal(out["src/skill.js"], "// Generated by vibelang from src/skill.vibe; the migrate flow writes it again with each batch.\nexport {}\n")
    assert.match(out["src/util.js"], /^\/\/ Generated by vibelang from src\/util\.ts;/)
    // Outside the package: a tracked file is put back, a new one removed, a sidecar left as the compile wrote it.
    const after = tree(root, [".bin", "packages/schema/.vibelang"])
    assert.deepEqual(after, { ...before, "packages/stories/config.d.vibe.ts": "export {}\n" })
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

// Generated packages: sources of each kind, tests, outputs with no source,
// nested directories. The kept set is exactly the non-test outputs with a source.
const kinds = [".vibe", ".ts", ".tsx", ".mts", null]
const dirs = ["src", "src/deep", "lib", "test", "src/__tests__"]
test("emitted-js-selection: the emit keeps exactly the JavaScript of the package's non-test sources", async () => {
  await fc.assert(fc.asyncProperty(fc.uniqueArray(fc.record({ dir: fc.constantFrom(...dirs), name: fc.constantFrom("a", "b.c", "x-y", "a.test", "b.spec"), kind: fc.constantFrom(...kinds) }), { selector: (m) => m.dir + "/" + m.name, maxLength: 8 }), async (modules) => {
    const root = mkdtempSync(join(tmpdir(), "migrate-emitted-js-"))
    try {
      const files = { "pkg/package.json": "{}" }
      for (const m of modules) if (m.kind) files[`pkg/${m.dir}/${m.name}${m.kind}`] = ""
      write(root, files)
      const bin = fakeCompiler(root, modules.map((m) => ({ path: `${m.dir}/${m.name}.js` })))
      await emitPackageJs({ compiler: bin, tsconfigs: ["tsconfig.json"], packageDir: join(root, "pkg"), root })
      const kept = existsSync(join(root, "pkg/.vibelang/js")) ? Object.keys(tree(join(root, "pkg/.vibelang/js"))).sort() : []
      const expected = modules.filter((m) => m.kind && !/(?:^|\/)(?:test|__tests__)(?:\/|$)/.test(m.dir) && !/\.(?:test|spec)$/.test(m.name)).map((m) => `${m.dir}/${m.name}.js`).sort()
      assert.deepEqual(kept, expected)
    } finally {
      rmSync(root, { recursive: true, force: true })
    }
  }), { seed: 36036, numRuns: 60 })
})

// opencode-32, end to end with the real compiler: @opencode/schema's
// `"./*": "./src/*.ts"` after a batch migrates skill.ts, which imports a
// TypeScript helper; an app imports @opencode/schema/skill.
test("a migrated package's exports and emit let plain node and the bun build CLI read it", { skip: !compiler && "set VIBELANG_BINARY" }, async (t) => {
  assert.ok(readFileSync(new URL("../README.md", import.meta.url), "utf8").includes(quote), "update the quoted exports rule")
  const corpus = JSON.parse(readFileSync(new URL("./corpus/opencode-schema-bun-build.json", import.meta.url), "utf8"))
  const root = realpathSync(mkdtempSync(join(tmpdir(), "migrate-emitted-js-")))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  write(root, corpus.files)
  mkdirSync(join(root, "node_modules/@opencode"), { recursive: true })
  symlinkSync(join(root, "packages/schema"), join(root, "node_modules/@opencode/schema"))
  const renames = renameBatch(root, ["packages/schema/src/skill.ts"])
  rewriteExports(root, renames)
  assert.deepEqual(JSON.parse(readFileSync(join(root, "packages/schema/package.json"), "utf8")).exports, corpus.exports)
  const packageDir = join(root, "packages/schema")
  const emitted = await emitPackageJs({ compiler, tsconfigs: ["tsconfig.json"], packageDir, root })
  assert.equal(emitted.files, 2, JSON.stringify(emitted.diagnostics))
  const node = spawnSync(process.execPath, ["main.mjs"], { cwd: join(root, "packages/app"), encoding: "utf8" })
  assert.equal(node.stdout.trim(), corpus.prints, node.stderr)
  if (hasBun) {
    const built = spawnSync("bun", ["build", "main.mjs", "--target=bun", "--packages=bundle", `--outdir=${join(root, "out")}`], { cwd: join(root, "packages/app"), encoding: "utf8" })
    assert.equal(built.status, 0, built.stderr)
    const run = spawnSync("bun", [join(root, "out/main.js")], { encoding: "utf8" })
    assert.equal(run.stdout.trim(), corpus.prints, run.stderr)
  }
})

// opencode cold start: with the emitted JavaScript, the emit step writes the
// loader record of the package's project, which a cold loader uses in place
// of the compile (packages/compiler/test/loader-record.test.mjs).
test("the emit step writes each loader project's record, which a cold lookup accepts", { skip: !compiler && "set VIBELANG_BINARY" }, async (t) => {
  const corpus = JSON.parse(readFileSync(new URL("./corpus/opencode-schema-bun-build.json", import.meta.url), "utf8"))
  const root = realpathSync(mkdtempSync(join(tmpdir(), "migrate-loader-record-")))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  write(root, corpus.files)
  rewriteExports(root, renameBatch(root, ["packages/schema/src/skill.ts"]))
  const packageDir = join(root, "packages/schema")
  await emitPackageJs({ compiler, tsconfigs: ["tsconfig.json"], packageDir, root })
  await new Promise((done) => setTimeout(done, 120))
  mkdirSync(join(root, "node_modules"), { recursive: true })
  symlinkSync(fileURLToPath(new URL("../../../../packages/compiler/", import.meta.url)), join(root, "node_modules/vibelang"))
  const records = await writeLoaderRecords({ compiler, packageDir, root })
  assert.deepEqual(records, [{ project: "packages/schema/tsconfig.json", file: "packages/schema/.vibelang/js/.loader/tsconfig.json.json", modules: 1 }])
  const project = join(packageDir, "tsconfig.json")
  const found = loaderRecord({ project, root: packageDir, compiler }).lookup()
  assert.equal(found.miss, undefined, found.miss)
  assert.ok(found.result.outputs.has(join(packageDir, "src/skill.vibe")))
})

// A toolchain build stages .smithers on its own, without the repository's
// packages or .smithers/node_modules (m12-opencode, drive2-opencode). The flow
// must load from such a copy with nothing to find by walking up: step.mjs runs
// before a target has vibelang installed. The record step alone needs vibelang,
// from the target: a target without it gets a receipt entry, not a failed emit.
function stageFlow(t) {
  const smithers = fileURLToPath(new URL("../../../", import.meta.url))
  const top = realpathSync(mkdtempSync(join(tmpdir(), "migrate-staged-flow-")))
  t.after(() => rmSync(top, { recursive: true, force: true }))
  const staged = join(top, "toolchain/.smithers")
  cpSync(join(smithers, "flows"), join(staged, "flows"), { recursive: true, filter: (path) => !/[\\/]node_modules(?:[\\/]|$)/.test(path.slice(smithers.length)) })
  const flow = join(staged, "flows/migrate")
  // The stage is only a proof if a dependency cannot be found above it.
  assert.throws(() => createRequire(join(flow, "lib/steps.mjs")).resolve("minimatch"), { code: "MODULE_NOT_FOUND" })
  return { top, flow }
}

test("the migrate flow loads every module and runs step.mjs from a stage with no node_modules in reach", (t) => {
  const { top, flow } = stageFlow(t)
  const modules = readdirSync(join(flow, "lib"), { recursive: true }).filter((file) => file.endsWith(".mjs"))
  assert.ok(modules.includes("source-paths.mjs") && modules.includes("steps.mjs"))
  const imports = modules.map((file) => `await import(${JSON.stringify(pathToFileURL(join(flow, "lib", file)).href)})`).join("\n")
  const loaded = spawnSync(process.execPath, ["--input-type=module", "-e", imports], { cwd: top, encoding: "utf8" })
  assert.equal(loaded.status, 0, loaded.stderr)
  const help = spawnSync(process.execPath, [join(flow, "step.mjs"), "help"], { cwd: top, encoding: "utf8" })
  assert.equal(help.status, 0, help.stderr)
  assert.match(help.stdout, /^usage: node \.smithers\/flows\/migrate\/step\.mjs/)
})

test("a staged flow's record step reports a target with no vibelang installed", async (t) => {
  const { top, flow } = stageFlow(t)
  const target = join(top, "target/packages/schema")
  write(target, { "package.json": "{}", "tsconfig.json": "{}", "src/skill.vibe": "export const skill = 1\n" })
  const probe = `const { writeLoaderRecords } = await import(${JSON.stringify(pathToFileURL(join(flow, "lib/declarations.mjs")).href)})
console.log(JSON.stringify(await writeLoaderRecords({ compiler: "vibelang", packageDir: ${JSON.stringify(target)}, root: ${JSON.stringify(join(top, "target"))} })))`
  const result = spawnSync(process.execPath, ["--input-type=module", "-e", probe], { cwd: top, encoding: "utf8" })
  assert.equal(result.status, 0, result.stderr)
  const [entry] = JSON.parse(result.stdout.trim().split("\n").at(-1))
  assert.equal(entry.package, "packages/schema")
  assert.match(entry.error, /^vibelang\/project is not installed for this package/)
})

test("a staged flow writes a loader record with only the target's installed vibelang in reach", { skip: !compiler && "set VIBELANG_BINARY" }, async (t) => {
  const { top, flow } = stageFlow(t)
  const root = join(top, "target")
  const target = join(root, "packages/schema")
  write(target, { "package.json": "{\"type\":\"module\"}", "tsconfig.json": "{\"compilerOptions\":{\"target\":\"ES2022\",\"module\":\"NodeNext\",\"moduleResolution\":\"NodeNext\",\"types\":[]},\"include\":[\"src/**/*\"]}", "src/skill.vibe": "export const skill: number = 1\n" })
  mkdirSync(join(root, "node_modules"), { recursive: true })
  symlinkSync(fileURLToPath(new URL("../../../../packages/compiler/", import.meta.url)), join(root, "node_modules/vibelang"))
  await new Promise((done) => setTimeout(done, 120))
  const probe = `const { writeLoaderRecords } = await import(${JSON.stringify(pathToFileURL(join(flow, "lib/declarations.mjs")).href)})
console.log(JSON.stringify(await writeLoaderRecords({ compiler: ${JSON.stringify(compiler)}, packageDir: ${JSON.stringify(target)}, root: ${JSON.stringify(root)} })))`
  const result = spawnSync(process.execPath, ["--input-type=module", "-e", probe], { cwd: top, encoding: "utf8" })
  assert.equal(result.status, 0, result.stderr)
  assert.deepEqual(JSON.parse(result.stdout.trim().split("\n").at(-1)), [{ project: "packages/schema/tsconfig.json", file: "packages/schema/.vibelang/js/.loader/tsconfig.json.json", modules: 1 }])
})

// A toolchain build stages .smithers on its own, without the repository's
// packages (m12-opencode). The flow must load from such a copy; its record step
// takes vibelang/project from the target's installed vibelang, and reports a
// target without one instead of failing the emit.
test("the migrate flow loads from a staged .smithers copy outside the repository", async (t) => {
  const smithers = fileURLToPath(new URL("../../../", import.meta.url))
  const top = realpathSync(mkdtempSync(join(tmpdir(), "migrate-staged-flow-")))
  t.after(() => rmSync(top, { recursive: true, force: true }))
  const staged = join(top, "toolchain/.smithers")
  cpSync(smithers, staged, { recursive: true, filter: (path) => !/(?:^|[\\/])node_modules(?:[\\/]|$)/.test(path.slice(smithers.length)) })
  symlinkSync(realpathSync(join(smithers, "node_modules")), join(staged, "node_modules"))
  const target = join(top, "target/packages/schema")
  write(target, { "package.json": "{}", "tsconfig.json": "{}", "src/skill.vibe": "export const skill = 1\n" })
  const lib = join(staged, "flows/migrate/lib")
  const probe = [
    `const { writeLoaderRecords } = await import(${JSON.stringify(pathToFileURL(join(lib, "declarations.mjs")).href)})`,
    `await import(${JSON.stringify(pathToFileURL(join(lib, "steps.mjs")).href)})`,
    `console.log(JSON.stringify(await writeLoaderRecords({ compiler: "vibelang", packageDir: ${JSON.stringify(target)}, root: ${JSON.stringify(join(top, "target"))} })))`
  ].join("\n")
  const result = spawnSync(process.execPath, ["--input-type=module", "-e", probe], { cwd: top, encoding: "utf8" })
  assert.equal(result.status, 0, result.stderr)
  const [entry] = JSON.parse(result.stdout.trim().split("\n").at(-1))
  assert.equal(entry.package, "packages/schema")
  assert.match(entry.error, /^vibelang\/project is not installed for this package/)
})
