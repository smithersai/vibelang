import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { test } from "node:test"
import { buildContext, replacements, skillBody } from "../build-context.mjs"

test("context.md is generated from its sources and current", () => {
  assert.equal(readFileSync(new URL("../context.md", import.meta.url), "utf8"), buildContext())
})

test("the context teaches the call rule, the skill, the cheat sheet, the examples and the platform table", () => {
  const context = buildContext()
  assert.ok(context.startsWith("<!-- Generated by build-context.mjs"))
  for (const part of ["## The call rule", "returns its Effect unrun", "try retry(fetchUser(id), policy)", "https://github.com/smithersai/vibelang/tree/main/docs/design/vips",
    "### Syntax cheat sheet", "#### 01-parcel-errors", "## Where this toolchain is behind the skill", "or `: infer _`, on each function and method the TypeScript declared plain", "### Platform globals and their replacements", "| `process.env` | `try Config.String(\"NAME\")` |", "### Forms", "### Rules"]) {
    assert.ok(context.includes(part), `the context lacks ${part}`)
  }
})

test("skillBody drops the front matter and nests headings; replacements needs its section", () => {
  assert.equal(skillBody("---\nname: x\n---\n# Skill\n\n## Forms\n"), "## Skill\n\n### Forms")
  assert.throws(() => replacements("# Page\n"), /Replacements/)
})


test("program combinators receive Effects while callback positions keep functions", () => {
  const context = buildContext()
  for (const part of ["retry(effect { return try fetchUser(id) }, policy)",
    "Effect.all([effect { return try load() }])", "Effect.forEach(ids, effect (id) => try load(id))"]) {
    assert.ok(context.includes(part), `the context lacks ${part}`)
  }
  assert.ok(!context.includes("only a function literal defers it"))
})
