// Setup's wiring for Metro, Babel and oxc-transform-react (lib/react-tools.mjs),
// on the shapes t3code's apps/mobile and apps/web have.
import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { test } from "node:test"
import { createRequire } from "node:module"
import { fileURLToPath, pathToFileURL } from "node:url"
import { loadTypeScript } from "../lib/declarations.mjs"
import { addBabelPreset, addMetroWrapper, addReactCompilerInclude, patchTransformEntry, unifiedDiff, wireReactTools } from "../lib/react-tools.mjs"

// The runtime package's install (bun install in packages/runtime) has TypeScript's compiler API and fast-check.
const fc = createRequire(new URL("../../../../packages/runtime/package.json", import.meta.url))("fast-check")
const ts = loadTypeScript([fileURLToPath(new URL("../../../../packages/runtime/", import.meta.url))])
const parses = (text, file) => ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS).parseDiagnostics.length === 0

function tree(t, files) {
  const root = mkdtempSync(join(tmpdir(), "react-tools-"))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), text)
  }
  return root
}

// t3code apps/mobile/metro.config.js, its export: a promise of the config.
const t3codeMetro = `const { getDefaultConfig } = require("expo/metro-config");
const config = getDefaultConfig(__dirname);
module.exports = Promise.all([generateMobileThirdPartyLicenses(), prepareStreamScripts()]).then(
  () =>
    withUniwindConfig(config, {
      cssEntryFile: "./global.css",
    }),
);
`
// t3code apps/mobile/babel.config.js.
const t3codeBabel = `module.exports = function (api) {
  api.cache(true);
  return {
    presets: [["babel-preset-expo", { unstable_transformImportMeta: true }]],
  };
};
`
// The tail napi-rs writes into oxc-transform-react 0.152.0's index.js.
const napiEntry = (binding) => `/* auto-generated by NAPI-RS */

import { createRequire } from 'module'
const require = createRequire(import.meta.url)

const nativeBinding = ${binding}
const { Severity, transform, transformSync } = nativeBinding
export { Severity }
export { transform }
export { transformSync }
export const __napiBindingTarget = 'test'
`

test("addMetroWrapper wraps the config module.exports gives, a promise included", () => {
  const wired = addMetroWrapper(t3codeMetro, ts)
  assert.ok(parses(wired, "metro.config.js"))
  assert.match(wired, /^module\.exports = require\("vibelang\/metro"\)\.withVibeLang\(Promise\.all\(\[generateMobileThirdPartyLicenses\(\), prepareStreamScripts\(\)\]\)\.then\([\s\S]*\}\),\n\)\);\n$/m)
  assert.equal(addMetroWrapper(wired, ts), wired)
})

test("addMetroWrapper imports withVibeLang for export default, in the file's quotes", () => {
  const text = `import { getDefaultConfig } from '@react-native/metro-config'\n\nexport default getDefaultConfig(import.meta.dirname)\n`
  assert.equal(addMetroWrapper(text, ts, "metro.config.mjs"), `import { getDefaultConfig } from '@react-native/metro-config'\nimport { withVibeLang } from 'vibelang/metro'\n\nexport default withVibeLang(getDefaultConfig(import.meta.dirname))\n`)
  assert.throws(() => addMetroWrapper("exports.resolver = {}\n", ts), /by hand/)
})

test("addBabelPreset adds vibelang/babel last to the presets, in JavaScript and JSON", () => {
  const wired = addBabelPreset(t3codeBabel, ts)
  assert.match(wired, /presets: \[\["babel-preset-expo", \{ unstable_transformImportMeta: true \}\], "vibelang\/babel"\],/)
  assert.equal(addBabelPreset(wired, ts), wired)
  assert.equal(addBabelPreset('{\n  "presets": ["module:@react-native/babel-preset"]\n}\n', ts, ".babelrc"), '{\n  "presets": [\n    "module:@react-native/babel-preset",\n    "vibelang/babel"\n  ]\n}\n')
  assert.throws(() => addBabelPreset("const presets = [];\nmodule.exports = { presets };\n", ts), /by hand/)
})

test("addReactCompilerInclude lets plugin-react's React Compiler see .vibe modules", () => {
  // t3code apps/web/vite.config.ts, its plugins.
  const text = `import react from "@vitejs/plugin-react";
import vibelang from "vibelang-vite";
export default defineConfig({
  plugins: [vibelang({ register: true }), tanstackRouter(), react({ compiler: true })],
});
`
  const wired = addReactCompilerInclude(text, ts)
  assert.equal(wired, text.replace("react({ compiler: true })", "react({ compiler: true, include: /\\.(?:[tj]sx?|vibe)$/ })"))
  assert.equal(addReactCompilerInclude(wired, ts), wired)
  assert.equal(addReactCompilerInclude(text.replace("{ compiler: true }", ""), ts), text.replace("{ compiler: true }", ""))
  assert.throws(() => addReactCompilerInclude(text.replace("compiler: true", "compiler: true, include: /x/"), ts), /by hand/)
})

test("the patched entry hands a .vibe module's source to vibelang/emit, resolved from the module", async (t) => {
  const root = tree(t, {
    "node_modules/oxc-transform-react/package.json": '{"name":"oxc-transform-react","version":"0.152.0","type":"module","main":"index.js"}',
    "node_modules/oxc-transform-react/index.js": patchTransformEntry(napiEntry("{ Severity: {}, transform: async (f, s, o) => ({ f, s, o }), transformSync: (f, s, o) => ({ f, s, o }) }")),
    // The app's vibelang, a stand-in for vibelang/emit's toolArguments.
    "app/node_modules/vibelang/package.json": '{"name":"vibelang","type":"module","exports":{"./emit":"./emit.mjs"}}',
    "app/node_modules/vibelang/emit.mjs": 'export const toolArguments = (f, s, o) => [f, "compiled:" + s, { ...o, lang: "jsx" }]\n'
  })
  const oxc = await import(pathToFileURL(join(root, "node_modules/oxc-transform-react/index.js")))
  const vibe = join(root, "app/src/a.vibe")
  assert.deepEqual(await oxc.transform(vibe, "source", { jsx: {} }), { f: vibe, s: "compiled:source", o: { jsx: {}, lang: "jsx" } })
  assert.deepEqual(oxc.transformSync(vibe, "source"), { f: vibe, s: "compiled:source", o: { lang: "jsx" } })
  assert.deepEqual(await oxc.transform(join(root, "app/src/a.ts"), "source", {}), { f: join(root, "app/src/a.ts"), s: "source", o: {} })
  assert.throws(() => patchTransformEntry("export const transform = 1\n"), /napi-rs/)
})

test("git applies unifiedDiff's patch: the edited file, whatever lines change", (t) => {
  const root = tree(t, {})
  const line = fc.constantFrom("a", "b", "c", "", "export { transform }", "  x")
  const file = fc.record({
    before: fc.array(line, { maxLength: 12 }),
    start: fc.nat(), deleted: fc.nat({ max: 4 }), inserted: fc.array(line, { maxLength: 4 }),
    newline: fc.boolean()
  }).filter(({ before, start, deleted, inserted }) => deleted + inserted.length > 0 && before.length > 0)
  let applied = 0
  fc.assert(fc.property(file, ({ before, start, deleted, inserted, newline }) => {
    const at = start % (before.length + 1)
    const after = [...before.slice(0, at), ...inserted, ...before.slice(at + deleted)]
    const text = (lines) => lines.join("\n") + (newline ? "\n" : "")
    if (text(before) === text(after) || after.length === 0) return
    writeFileSync(join(root, "index.js"), text(before))
    writeFileSync(join(root, "change.patch"), unifiedDiff("index.js", text(before), text(after)))
    // Inside a repository git applies paths from its root and skips the rest; root is no repository's.
    const git = spawnSync("git", ["apply", "change.patch"], { cwd: root, encoding: "utf8", env: { ...process.env, GIT_CEILING_DIRECTORIES: dirname(root) } })
    assert.equal(git.status, 0, git.stderr + readFileSync(join(root, "change.patch"), "utf8"))
    assert.equal(readFileSync(join(root, "index.js"), "utf8"), text(after))
    applied++
  }), { numRuns: 150, seed: 20261101 })
  assert.ok(applied > 50)
})

test("wireReactTools wires t3code's mobile and web apps for pnpm, once", (t) => {
  const root = tree(t, {
    "package.json": '{"name":"t3code","private":true,"packageManager":"pnpm@12.14.0"}\n',
    "pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
    "pnpm-workspace.yaml": "packages:\n  - apps/*\n\npatchedDependencies:\n  expo-audio@58.0.9: patches/expo-audio@58.0.9.patch\n",
    "apps/mobile/package.json": '{"name":"@t3tools/mobile","dependencies":{"@t3tools/contracts":"workspace:*"}}\n',
    "apps/mobile/metro.config.js": t3codeMetro,
    "apps/mobile/babel.config.js": t3codeBabel,
    "apps/web/package.json": '{"name":"@t3tools/web","dependencies":{"@t3tools/contracts":"workspace:*"},"devDependencies":{"oxc-transform-react":"0.152.0"}}\n',
    "apps/web/vite.config.ts": 'import react from "@vitejs/plugin-react";\nexport default defineConfig({ plugins: [react({ compiler: true })] });\n',
    "apps/web/node_modules/oxc-transform-react/package.json": '{"name":"oxc-transform-react","version":"0.152.0","type":"module","main":"index.js"}',
    "apps/web/node_modules/oxc-transform-react/index.js": napiEntry("{}"),
    "packages/contracts/package.json": '{"name":"@t3tools/contracts"}\n'
  })
  const specsFor = () => ({ vibelang: "0.0.11" })
  const wired = wireReactTools({ root, packages: [{ dir: "packages/contracts" }], ts, specsFor })
  assert.deepEqual(wired.warnings, [])
  assert.deepEqual(wired.changed.sort(), ["apps/mobile/babel.config.js", "apps/mobile/metro.config.js", "apps/mobile/package.json", "apps/web/vite.config.ts", "patches/oxc-transform-react@0.152.0.patch", "pnpm-workspace.yaml"])
  assert.equal(JSON.parse(readFileSync(join(root, "apps/mobile/package.json"), "utf8")).devDependencies.vibelang, "0.0.11")
  assert.match(readFileSync(join(root, "pnpm-workspace.yaml"), "utf8"), /patchedDependencies:\n  expo-audio@58\.0\.9: patches\/expo-audio@58\.0\.9\.patch\n  '?oxc-transform-react@0\.152\.0'?: patches\/oxc-transform-react@0\.152\.0\.patch\n/)
  const patch = readFileSync(join(root, "patches/oxc-transform-react@0.152.0.patch"), "utf8")
  assert.match(patch, /^diff --git a\/index\.js b\/index\.js\n--- a\/index\.js\n\+\+\+ b\/index\.js\n@@ /)
  assert.match(patch, /^\+export \{ vibelangTransform as transform \}$/m)
  // A rerun, with the installed entry patched, changes nothing.
  const entry = join(root, "apps/web/node_modules/oxc-transform-react/index.js")
  writeFileSync(entry, patchTransformEntry(readFileSync(entry, "utf8")))
  assert.deepEqual(wireReactTools({ root, packages: [{ dir: "packages/contracts" }], ts, specsFor }), { changed: [], warnings: [] })
})

test("wireReactTools leaves a repository whose manager has no patchedDependencies with a warning", (t) => {
  const root = tree(t, {
    "package.json": '{"name":"app","dependencies":{"oxc-transform-react":"0.152.0"}}\n',
    "package-lock.json": "{}\n",
    "node_modules/oxc-transform-react/package.json": '{"name":"oxc-transform-react","version":"0.152.0","type":"module","main":"index.js"}',
    "node_modules/oxc-transform-react/index.js": napiEntry("{}")
  })
  const wired = wireReactTools({ root, packages: [{ dir: "." }], ts, specsFor: () => ({ vibelang: "0.0.11" }) })
  assert.deepEqual(wired.changed, [])
  assert.match(wired.warnings.join("\n"), /oxc-transform-react@0\.152\.0: .*by hand; setup writes patchedDependencies for pnpm and Bun only/)
})
