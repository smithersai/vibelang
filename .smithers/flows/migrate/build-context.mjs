// Writes context.md, the repair agent's system prompt, from its sources. It is
// generated, never hand-edited:
//   rules.md                                     the migration's own rules (edit this)
//   packages/compiler/skills/vibelang/SKILL.md   every form and rule of the language
//   ../convert/                                  the convert flow's cheat sheet and worked examples
//   docs/user/src/platform/platform-globals.md   each platform global's replacement
//
//   node .smithers/flows/migrate/build-context.mjs           write context.md
//   node .smithers/flows/migrate/build-context.mjs --check   exit 1 if context.md is stale
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { cheatSheet, exampleCases } from "../convert/build-prompt.mjs"

const here = fileURLToPath(new URL(".", import.meta.url))
const root = join(here, "../../..")
const read = (path) => readFileSync(join(root, path), "utf8")

/** The skill without its front matter, its headings one level down. */
export function skillBody(skill = read("packages/compiler/skills/vibelang/SKILL.md")) {
  const body = skill.replace(/^---\n[\s\S]*?\n---\n/, "").trim()
  return body.replace(/^(#+) /gm, "#$1 ")
}

/** The Replacements section of the platform globals page: one row per global. */
export function replacements(page = read("docs/user/src/platform/platform-globals.md")) {
  const start = page.indexOf("## Replacements")
  const end = page.indexOf("\n## ", start + 1)
  if (start < 0 || end < 0) throw new Error("platform-globals.md has no \"## Replacements\" section")
  return page.slice(start, end).trim().replace(/^## Replacements/, "### Platform globals and their replacements")
}

export function buildContext() {
  const rules = readFileSync(join(here, "rules.md"), "utf8").trim()
  const examples = exampleCases().map((c) => `#### ${c.name}\n\nEffect TypeScript:\n\n\`\`\`ts\n${c.input}\n\`\`\`\n\nVibeLang:\n\n\`\`\`vibe\n${c.expected}\n\`\`\``)
  return `<!-- Generated by build-context.mjs from rules.md, the VibeLang skill, the convert flow's cheat sheet and examples, and the platform globals page. Do not edit. -->
${rules}

## The language

The VibeLang skill follows: every form beside the Effect code it replaces, and the rules with their EK codes. Accepted VIPs and the call rule above take precedence over older examples.

${skillBody()}

## The convert flow's cheat sheet

${cheatSheet().replace(/^## Syntax cheat sheet/, "### Syntax cheat sheet")}

## Worked examples

Each pair is one Effect TypeScript file and the VibeLang that replaces it.

${examples.join("\n\n")}

## Platform

${replacements()}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = join(here, "context.md")
  const next = buildContext()
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(target, "utf8") } catch { return "" } })()
    if (current !== next) { console.error("context.md is stale: run node .smithers/flows/migrate/build-context.mjs"); process.exit(1) }
    console.log("context.md is up to date")
  } else {
    writeFileSync(target, next)
    console.log(`wrote context.md (${Buffer.byteLength(next)} bytes)`)
  }
}
