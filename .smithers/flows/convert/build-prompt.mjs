// Writes prompt.md, the convert flow's system prompt: rules, the cheat sheet from
// .smithers/instructions/app.md, and the separate examples/ pairs. Generated, never hand-edited.
//   node .smithers/flows/convert/build-prompt.mjs           write prompt.md
//   node .smithers/flows/convert/build-prompt.mjs --check   exit 1 if prompt.md is stale
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { casesIn } from "./cases.mjs"

const here = fileURLToPath(new URL(".", import.meta.url))
const root = join(here, "../../..")

export function cheatSheet(app = readFileSync(join(root, ".smithers/instructions/app.md"), "utf8")) {
  const start = app.indexOf("## Syntax cheat sheet")
  const end = app.indexOf("\n## ", start + 1)
  if (start < 0 || end < 0) throw new Error("app.md has no \"## Syntax cheat sheet\" section")
  return app.slice(start, end).trim()
}

export function exampleCases(dir = join(here, "examples")) {
  return casesIn(dir)
}

export function buildPrompt() {
  const examples = exampleCases().map((c) => `### ${c.name}\n\nInput:\n\n\`\`\`ts\n${c.input}\n\`\`\`\n\nOutput:\n\n\`\`\`ts\n${c.expected}\n\`\`\``)
  return `<!-- Generated by build-prompt.mjs from instructions/app.md and examples/. Do not edit. -->
# Convert Effect TypeScript to VibeLang

You convert one Effect 4 TypeScript file into the equivalent VibeLang file.

Answer with exactly one fenced \`ts\` code block holding the whole VibeLang file, and nothing else.

- Keep every export, with its name and type. An exported \`Effect\` value stays a lazy \`Effect\`-valued \`const\`: use an \`effect { … }\` block, never a function that consumers must call.
- Drop imports from \`"effect"\`: VibeLang has Effect's root modules and common functions in scope.
- Use the VibeLang forms below wherever the input uses the Effect form they replace.
- Keep the program's behavior. Add nothing the input does not do, and do not explain.

${cheatSheet().replace(/^## /m, "## ")}

## Examples

${examples.join("\n\n")}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = join(here, "prompt.md")
  const next = buildPrompt()
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(target, "utf8") } catch { return "" } })()
    if (current !== next) { console.error("prompt.md is stale: run node .smithers/flows/convert/build-prompt.mjs"); process.exit(1) }
    console.log("prompt.md is up to date")
  } else {
    writeFileSync(target, next)
    console.log(`wrote prompt.md (${Buffer.byteLength(next)} bytes, ${exampleCases().length} examples)`)
  }
}
