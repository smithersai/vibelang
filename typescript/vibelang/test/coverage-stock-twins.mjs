// Rebuild concurrency coverage references with TypeScript 5.9.3 / Effect 4.1.0.
// COVERAGE_REFERENCE_NODE_MODULES must hold exactly those packages.
// COVERAGE_REFERENCE_SCRATCH selects the on-disk staging directory.
import assert from "node:assert/strict"
import fs from "node:fs"
import path from "node:path"
import { spawnSync } from "node:child_process"
import { fileURLToPath, pathToFileURL } from "node:url"

const here = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const casesRoot = path.join(here, "cases")
const generated = "Generated by typescript/vibelang/coverage-stock-twins.mjs from typescript/main.ts."
const normalizeTypes = text => text.replace(/^\/\/.*$/gm, "").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s+/g, "")

// These witnesses return deterministic plain values. Keep the live native
// twin's raw Exit comparison too: JSON alone would merge undefined and null.
export function checkStockTwin(caseURL, actual) {
  const dir = path.dirname(fileURLToPath(caseURL))
  const stock = JSON.parse(fs.readFileSync(path.join(dir, "stock-exit.json"), "utf8"))
  assert.equal(stock.typescript, "5.9.3")
  assert.equal(stock.effect, "4.1.0")
  assert.deepEqual(JSON.parse(JSON.stringify(actual)), stock.exit, "Exit differs from TypeScript 5.9.3 / Effect 4.1.0")
  const actualTypes = fs.readFileSync(path.join(dir, "out/main.d.ts"), "utf8")
  const stockTypes = fs.readFileSync(path.join(dir, "stock-types.txt"), "utf8")
  assert.equal(normalizeTypes(actualTypes), normalizeTypes(stockTypes), "public types differ from the stock TypeScript twin")
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, encoding: "utf8", timeout: 120000, maxBuffer: 4 * 1024 * 1024 })
  if (result.error || result.status !== 0) {
    throw new Error(String(result.error || command + " exited " + result.status) + "\n" + result.stdout + result.stderr)
  }
  return result.stdout
}

function writeTwins(names) {
  const modules = process.env.COVERAGE_REFERENCE_NODE_MODULES
  assert.ok(modules, "set COVERAGE_REFERENCE_NODE_MODULES to TypeScript 5.9.3 / Effect 4.1.0")
  for (const [name, version] of [["typescript", "5.9.3"], ["effect", "4.1.0"]]) {
    assert.equal(JSON.parse(fs.readFileSync(path.join(modules, name, "package.json"))).version, version)
  }
  const scratch = process.env.COVERAGE_REFERENCE_SCRATCH || path.join(here, "../.cache/coverage-stock")
  fs.mkdirSync(scratch, { recursive: true })
  for (const name of names) {
    assert.match(name, /^[a-z0-9.-]+$/)
    const dir = path.join(casesRoot, name)
    const reference = path.join(dir, "typescript")
    if (!fs.existsSync(path.join(reference, "main.ts"))) continue
    const stage = fs.mkdtempSync(path.join(scratch, "twin-"))
    try {
      for (const entry of fs.readdirSync(reference)) {
        if (entry.endsWith(".ts")) fs.copyFileSync(path.join(reference, entry), path.join(stage, entry))
      }
      fs.copyFileSync(path.join(reference, "tsconfig.json"), path.join(stage, "tsconfig.json"))
      fs.writeFileSync(path.join(stage, "package.json"), '{"type":"module"}\n')
      fs.symlinkSync(modules, path.join(stage, "node_modules"), "dir")
      run(process.execPath, [path.join(modules, "typescript/bin/tsc"), "-p", stage], stage)
      const script = 'import {Effect} from "effect"; import {main} from "./out/main.js"; console.log("@@stock-exit "+JSON.stringify(await Effect.runPromiseExit(main())))'
      const output = run(process.execPath, ["--input-type=module", "-e", script], stage)
      const line = output.split("\n").find(line => line.startsWith("@@stock-exit "))
      assert.ok(line, name + " reference produced no Exit")
      const exit = JSON.parse(line.slice("@@stock-exit ".length))
      fs.writeFileSync(path.join(dir, "stock-exit.json"), JSON.stringify({ generated, typescript: "5.9.3", effect: "4.1.0", exit }, null, 2) + "\n")
      fs.writeFileSync(path.join(dir, "stock-types.txt"), "// " + generated + "\n" + fs.readFileSync(path.join(stage, "out/main.d.ts"), "utf8"))
      console.log(name + ": stock types and Exit recorded")
    } finally {
      fs.rmSync(stage, { recursive: true, force: true })
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  assert.equal(process.argv[2], "--write", "usage: node coverage-stock-twins.mjs --write case...")
  writeTwins(process.argv.slice(3))
}
