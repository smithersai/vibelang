// Package effectglobals holds the globals of a .vibe file that Effect's
// Effect module supplies (VIP-6): every export of effect/Effect, such as
// retry, sleep, tryPromise, sync, and callback, is a global, and the emitted
// JavaScript imports each one a file uses from effect/Effect. A local
// declaration or an import shadows one, as it does any global, and the
// project setting vibe.effectGlobals: false turns them all off.
//
// An export whose name clashes is not a global, and a .vibe file writes it
// Effect.x instead. A name clashes when it is a reserved word (try, catch,
// void, let), a JavaScript global (undefined), or a VibeLang keyword (match,
// when, provide, service); Clash says which.
//
// Exports lists the exports of effect/Effect. It is generated from the
// installed effect package's dist/Effect.d.ts by ./gen, which
// scripts/build-vibelang.sh runs, so an Effect upgrade updates it;
// TestExportsMatchEffect checks it.
package effectglobals

import (
	"regexp"
	"slices"
	"strings"

	"github.com/microsoft/TypeScript/tsc/internal/ast"
	"github.com/microsoft/TypeScript/tsc/internal/parser"
	"github.com/microsoft/TypeScript/tsc/internal/scanner"
)

// Names are the exports of effect/Effect that are globals of a .vibe file.
var Names = func() map[string]bool {
	names := map[string]bool{}
	for _, name := range Exports {
		if Clash(name) == "" {
			names[name] = true
		}
	}
	return names
}()

// javaScriptGlobals are the value and function properties of ECMAScript's
// global object (ECMA-262, sections 19.1 and 19.2). Its constructors and
// namespaces are capitalized, as no Effect function is.
var javaScriptGlobals = []string{
	"globalThis", "Infinity", "NaN", "undefined",
	"eval", "isFinite", "isNaN", "parseFloat", "parseInt",
	"decodeURI", "decodeURIComponent", "encodeURI", "encodeURIComponent",
}

// Clash says why name, an export of effect/Effect, is not a global: "a
// reserved word", "a JavaScript global", or "a VibeLang keyword". It returns
// "" for a name that is a global.
func Clash(name string) string {
	switch kind := scanner.GetIdentifierToken(name); {
	case kind != ast.KindIdentifier && (!ast.IsContextualKeyword(kind) || ast.KindFirstFutureReservedWord <= kind && kind <= ast.KindLastFutureReservedWord):
		return "a reserved word"
	case slices.Contains(javaScriptGlobals, name):
		return "a JavaScript global"
	case slices.Contains(parser.VibeLangKeywords, name):
		return "a VibeLang keyword"
	}
	return ""
}

// ParseExports returns the value exports that declarations, the text of
// effect's dist/Effect.d.ts, declares, sorted: each export declare const,
// function, or class, and each name an export { local as name } gives a
// declaration whose own name is a reserved word, as try_ as try does.
func ParseExports(declarations string) []string {
	source := regexp.MustCompile(`(?s)/\*.*?\*/`).ReplaceAllString(declarations, "")
	var names []string
	for _, m := range regexp.MustCompile(`(?m)^export declare (?:const|function|class) ([A-Za-z_$][\w$]*)`).FindAllStringSubmatch(source, -1) {
		names = append(names, m[1])
	}
	for _, m := range regexp.MustCompile(`(?m)^export \{([^}]*)\}`).FindAllStringSubmatch(source, -1) {
		for _, specifier := range strings.Split(m[1], ",") {
			switch fields := strings.Fields(specifier); {
			case len(fields) == 3 && fields[1] == "as":
				names = append(names, fields[2])
			case len(fields) == 1:
				names = append(names, fields[0])
			}
		}
	}
	slices.Sort(names)
	return slices.Compact(names)
}

// Generated returns the text of exports_generated.go for exports, the
// exports of effect@version's Effect module.
func Generated(version string, exports []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by ./gen from effect@" + version + " dist/Effect.d.ts. DO NOT EDIT.\n\n")
	b.WriteString("package effectglobals\n\n")
	b.WriteString("// Exports are the value exports of effect/Effect, sorted.\n")
	b.WriteString("var Exports = []string{\n")
	for _, name := range exports {
		b.WriteString("\t\"" + name + "\",\n")
	}
	b.WriteString("}\n")
	return b.String()
}
