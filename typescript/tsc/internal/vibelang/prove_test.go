// Verification expressions print as Appendix F "Printing" says: each
// operator in parentheses, && split into lines, every and some as
// quantifiers over a fresh index, if conditions as implications, and each
// const replaced by its initializer.
func TestLowerProofsFormulas(t *testing.T) {
	source := `export function check(xs: readonly number[], k0: number): number {
  proof {
    assume(xs.every((x, i) => x >= i && k0 > 0))
    ensures((r) => r >= 0 && xs.some((y) => y === r))
  }
  const n = xs.length
  proof {
    const m = n - 1
    if (m >= 0) {
      assert(xs[m] >= 0)
    } else assert(!(n > 0))
    assert(m < n && n >= 0)
  }
  return n > 0 ? xs[0] : 0
}
`
	modules := lowerProofsOf(t, map[string]string{"check.vibe": source})
	if len(modules) != 1 {
		t.Fatalf("got %d modules", len(modules))
	}
	for _, line := range []string{
		"    //@ requires forall(k1: nat, ((k1 < xs.length) ==> ((xs[k1] >= k1) && (k0 > 0))))",
		"    //@ ensures (\\result >= 0)",
		"    //@ ensures exists(k1: nat, ((k1 < xs.length) && (xs[k1] === \\result)))",
		"    //@ assert (((n - 1) >= 0) ==> (xs[(n - 1)] >= 0))",
		"    //@ assert ((!((n - 1) >= 0)) ==> (!(n > 0)))",
		"    //@ assert ((n - 1) < n)",
		"    //@ assert (n >= 0)",
	} {
		if !strings.Contains(modules[0].Text, line+"\n") {
			t.Errorf("lowering has no line %q:\n%s", line, modules[0].Text)
		}
	}
}

// A proof block that nothing follows in its block gets {} after its lines,
// because LemmaScript 0.6.6 drops a trailing //@ assert.
func TestLowerProofsTrailingProofBlock(t *testing.T) {
	modules := lowerProofsOf(t, map[string]string{"main.vibe": "export function only(n: number): void {\n  if (n > 0) {\n    proof { assert(n > 0) }\n  }\n}\n"})
	if len(modules) != 1 || !strings.Contains(modules[0].Text, "        //@ assert (n > 0)\n        {}\n") {
		t.Fatalf("lowering:\n%v", modules)
	}
}

// A root copies what it reaches, from any module, ordered by module path and
// then position: types, primitive constants, checked functions, and trusted
// functions with //@ extern, //@ pure for a declare function.
func TestLowerProofsCopiesReachedDeclarations(t *testing.T) {
	modules := lowerProofsOf(t, map[string]string{
		"a.vibe": `import { limit, Score, clampScore } from "./b.js"
import { external } from "./c.js"
declare function matches(text: string, pattern: string): boolean
spec function valid(s: Score, text: string): boolean {
  return clampScore(s.value) <= limit && matches(text, "x") && external(s.value) >= 0
}
export function use(s: Score): number {
  proof { assume(valid(s, "a")) }
  return s.value
}
`,
		"b.vibe": `export const limit = 10
export interface Score { readonly value: number }
export function clampScore(n: number): number {
  return n > limit ? limit : n
}
export function unrelated(): number { return 1 }
`,
		"c.ts": "export function external(n: number): number { return n }\n",
	})
	if len(modules) != 1 {
		t.Fatalf("got %d modules", len(modules))
	}
	text := modules[0].Text
	want := []string{
		"// Generated by vibelang prove from a.vibe. Do not edit.\n",
		"//@ extern\n//@ pure\ndeclare function matches(text: string, pattern: string): boolean;\n",
		"// a.vibe:4\nexport function valid(",
		"// a.vibe:7\nexport function use(s: Score): number {\n    //@ verify\n    //@ requires valid(s, \"a\")\n",
		"export const limit = 10;\n",
		"export interface Score {\n",
		"// b.vibe:3\nexport function clampScore(n: number): number {\n    //@ verify\n",
		"//@ extern\ndeclare function external(n: number): number;\n",
	}
	last := -1
	for _, w := range want[:4] {
		if !strings.Contains(text, w) {
			t.Errorf("lowering has no %q:\n%s", w, text)
		}
	}
	for _, w := range want[4:] {
		i := strings.Index(text, w)
		if i < 0 {
			t.Errorf("lowering has no %q:\n%s", w, text)
		} else if i < last {
			t.Errorf("%q is out of order:\n%s", w, text)
		} else {
			last = i
		}
	}
	if strings.Contains(text, "unrelated") {
		t.Errorf("lowering copies a declaration no root reaches:\n%s", text)
	}
	var trusted []string
	for _, d := range modules[0].Trusted {
		trusted = append(trusted, d.Name)
		if d.Name == "external" != d.Imported {
			t.Errorf("%s Imported = %v", d.Name, d.Imported)
		}
	}
	if strings.Join(trusted, " ") != "matches external" {
		t.Errorf("trusted %v, want [matches external]", trusted)
	}
}
