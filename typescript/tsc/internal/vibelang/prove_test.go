// lowerProofsOf lowers the program of sources, .vibe and .ts files of one
// project, failing on any error diagnostic.
func lowerProofsOf(t *testing.T, sources map[string]string) []ProofModule {
	t.Helper()
	files := computedKeyFiles(false)
	files["/workspace/x/src/tsconfig.json"] = `{"compilerOptions":{"strict":true,"target":"ESNext","module":"NodeNext"},"include":["*.vibe","*.ts"]}`
	for name, text := range sources {
		files["/workspace/x/src/"+name] = text
	}
	p := computedKeyProgram(t, files)
	for _, d := range p.GetSemanticDiagnostics(t.Context(), nil) {
		if d.Category() == diagnostics.CategoryError {
			t.Fatalf("source: %s", d.String())
		}
	}
	c, done := p.GetTypeChecker(t.Context())
	defer done()
	return LowerProofs(p, c, "/workspace/x/src")
}

const countSource = `spec function countPrefix(xs: readonly boolean[], end: number): number {
  proof {
    assume(0 <= end && end <= xs.length)
    ensures((r) => 0 <= r && r <= end)
    decreases(end)
  }
  if (end <= 0) return 0
  return countPrefix(xs, end - 1) + (xs[end - 1] ? 1 : 0)
}

export function count(xs: readonly boolean[]): number {
  proof {
    ensures((r) => r === countPrefix(xs, xs.length))
  }
  let total = 0
  for (let i = 0; i < xs.length; i++) {
    proof {
      invariant(0 <= i && i <= xs.length)
      invariant(total === countPrefix(xs, i))
      decreases(xs.length - i)
    }
    if (xs[i]) total++
  }
  return total
}
`

// The lowering of a spec function and a checked function, as Appendix F
// "The lowering file" writes it. lemmascript 0.6.6 with Dafny 4.11.0
// verifies this text: 5 verified, 0 errors.
const countLowering = `// Generated by vibelang prove from count.vibe. Do not edit.
// count.vibe:1
export function countPrefix(xs: readonly boolean[], end: number): number {
    //@ verify
    //@ requires (0 <= end)
    //@ requires (end <= xs.length)
    //@ ensures (0 <= \result)
    //@ ensures (\result <= end)
    //@ decreases end
    if (end <= 0)
        return 0;
    return countPrefix(xs, end - 1) + (xs[end - 1] ? 1 : 0);
}
// count.vibe:11
export function count(xs: readonly boolean[]): number {
    //@ verify
    //@ ensures (\result === countPrefix(xs, xs.length))
    let total = 0;
    for (let i = 0; i < xs.length; i++) {
        //@ invariant (0 <= i)
        //@ invariant (i <= xs.length)
        //@ invariant (total === countPrefix(xs, i))
        //@ decreases (xs.length - i)
        if (xs[i])
            total++;
    }
    return total;
}
`

func TestLowerProofsSpecFunctionAndLoop(t *testing.T) {
	modules := lowerProofsOf(t, map[string]string{"count.vibe": countSource})
	if len(modules) != 1 {
		t.Fatalf("got %d modules, want 1", len(modules))
	}
	m := modules[0]
	if m.Source != "count.vibe" {
		t.Errorf("source %q, want count.vibe", m.Source)
	}
	if m.Text != countLowering {
		t.Errorf("lowering:\n%s\nwant:\n%s", m.Text, countLowering)
	}
	var roots []string
	for _, r := range m.Roots {
		roots = append(roots, r.Name+":"+strconv.Itoa(r.Line))
	}
	if got := strings.Join(roots, " "); got != "countPrefix:1 count:11" {
		t.Errorf("roots %s", got)
	}
}

