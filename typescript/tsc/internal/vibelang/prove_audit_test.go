// The Dafny that LemmaScript 0.6.6 generates for the lowering of
// searchSource, by its shape: a method for the procedure linearSearch, with
// its two postconditions, and a method for the method-form theorem, with
// its assertion.
const searchDafny = `// Generated by lsc from search.vibe.ts
include "lemmascript.dfy"

method linearSearch(xs: seq<int>, target: int) returns (res: int)
  ensures res < |xs|
  ensures res < 0 || xs[res] == target
{
  var i := 0;
  while i < |xs|
    invariant 0 <= i
    invariant i <= |xs|
    decreases |xs| - i
  {
    if xs[i] == target {
      return i;
    }
    i := i + 1;
  }
  return -1;
}

method searchFinds(xs: seq<int>, target: int) returns (res: bool)
{
  var index := linearSearch(xs, target);
  assert index >= 0 ==> xs[index] == target;
  return true;
}
`

// The Dafny for clampSource: a function for the transparent clamp, and for
// the lemma-form theorem a function and the lemma that carries its ensures.
const clampDafny = `function clamp(x: int, lo: int, hi: int): int
{
  if x < lo then lo else if x > hi then hi else x
}

function clampInRange(x: int, lo: int, hi: int): bool
  requires lo <= hi
{
  true
}

lemma clampInRange_ensures(x: int, lo: int, hi: int)
  requires lo <= hi
  ensures lo <= clamp(x, lo, hi)
  ensures clamp(x, lo, hi) <= hi
{
}
`

func auditMessages(findings []proofAuditFinding) []string {
	var messages []string
	for _, f := range findings {
		name := "<module>"
		if f.function != nil {
			name = f.function.Name
		}
		messages = append(messages, fmt.Sprintf("EK%d %s: %s", f.message.Code, name, format(f.message.Text, f.args)))
	}
	return messages
}

// Step 6, obligations and classification: the generated Dafny holds each
// function's assert statements and ensures clauses, and a function for each
// transparent function and a method for each procedure.
func TestProofAuditGeneratedDafny(t *testing.T) {
	search := lowerProofsOf(t, map[string]string{"search.vibe": searchSource})[0]
	clamp := lowerProofsOf(t, map[string]string{"clamp.vibe": clampSource})[0]
	var info lemmaScriptInfo
	for _, tc := range []struct {
		name      string
		functions []ProofFunction
		dafny     string
		want      []string // a part of each finding's message, in order
	}{
		{"the generation holds everything", search.Functions, searchDafny, nil},
		{"the lemma form", clamp.Functions, clampDafny, nil},
		{"a lost postcondition", search.Functions, strings.Replace(searchDafny, "  ensures res < |xs|\n", "", 1), []string{"EK4317 linearSearch: LemmaScript's Dafny for linearSearch holds 1 assert statements and ensures clauses, and the lowering wrote 2"}},
		{"a lost assertion", search.Functions, strings.Replace(searchDafny, "  assert index >= 0 ==> xs[index] == target;\n", "", 1), []string{"EK4317 searchFinds: LemmaScript's Dafny for searchFinds holds 0 assert statements and ensures clauses, and the lowering wrote 1"}},
		{"a lost lemma", clamp.Functions, clampDafny[:strings.Index(clampDafny, "lemma ")], []string{"EK4317 clampInRange: LemmaScript's Dafny for clampInRange holds 0 assert statements and ensures clauses, and the lowering wrote 2"}},
		{"an added postcondition", clamp.Functions, strings.Replace(clampDafny, "  ensures lo <= clamp(x, lo, hi)\n", "  ensures lo <= clamp(x, lo, hi)\n  ensures true\n", 1), []string{"holds 3 assert statements and ensures clauses, and the lowering wrote 2"}},
		{"a function for a procedure", search.Functions, strings.Replace(searchDafny, "method linearSearch(xs: seq<int>, target: int) returns (res: int)", "function linearSearch(xs: seq<int>, target: int): int", 1), []string{"EK4317 linearSearch: LemmaScript emits linearSearch as a Dafny function, and VibeLang classifies it as a procedure, which is a Dafny method"}},
		{"a method for a transparent function", clamp.Functions, strings.Replace(clampDafny, "function clamp(x: int, lo: int, hi: int): int", "method clamp(x: int, lo: int, hi: int) returns (res: int)", 1), []string{"EK4317 clamp: LemmaScript emits clamp as a Dafny method, and VibeLang classifies it as a transparent function, which is a Dafny function"}},
		{"a predicate is a function", clamp.Functions, strings.Replace(clampDafny, "function clampInRange(x: int, lo: int, hi: int): bool", "ghost predicate clampInRange(x: int, lo: int, hi: int)", 1), nil},
		{"a missing member", search.Functions, searchDafny[:strings.Index(searchDafny, "method searchFinds")], []string{"EK4317 searchFinds: LemmaScript's Dafny holds no member for searchFinds"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := auditMessages(auditGeneratedDafny(tc.functions, info, tc.dafny))
			if len(got) != len(tc.want) {
				t.Fatalf("got %d findings, want %d: %v", len(got), len(tc.want), got)
			}
			for i, want := range tc.want {
				if !strings.Contains(got[i], want) {
					t.Errorf("finding %d is %q, want it to hold %q", i, got[i], want)
				}
			}
		})
	}
}

// The member for a function is the one lsc info --typed names for it.
func TestProofAuditUsesEmittedNames(t *testing.T) {
	clamp := lowerProofsOf(t, map[string]string{"clamp.vibe": clampSource})[0]
	renamed := strings.NewReplacer("clampInRange_ensures", "clampInRange__ensures", "function clamp(", "function clamp_(").Replace(clampDafny)
	if got := auditMessages(auditGeneratedDafny(clamp.Functions, lemmaScriptInfo{}, renamed)); len(got) != 2 {
		t.Fatalf("without the emitted names: %v", got)
	}
	info, ok := parseLemmaScriptInfo("note\n" + `{"schema": 1, "functions": [{"name": "clamp", "isPure": true}], "dafny": {"emittedNames": {"clamp": "clamp_", "clampInRange": "clampInRange", "clampInRange_ensures": "clampInRange__ensures"}}}`)
	if !ok {
		t.Fatal("the info did not parse")
	}
	if got := auditMessages(auditGeneratedDafny(clamp.Functions, info, renamed)); len(got) != 0 {
		t.Fatalf("with the emitted names: %v", got)
	}
	if _, ok := parseLemmaScriptInfo("error: no JSON here"); ok {
		t.Fatal("text without JSON parsed")
	}
	if info, ok := parseLemmaScriptInfo(`{"dafny": {"error": "unsupported"}}`); !ok || info.Dafny.Error != "unsupported" {
		t.Fatalf("got %+v", info)
	}
}

// Step 6, assumptions: dafny audit reports nothing for P.dfy that it does
// not report for P.dfy.gen, compared by member and message.
func TestProofAuditAssumptions(t *testing.T) {
	clamp := lowerProofsOf(t, map[string]string{"clamp.vibe": clampSource})[0]
	generated := clampDafny + "\nlemma {:axiom} SplitAxiom()\n  ensures true\n"
	generatedOutput := "clamp.vibe.gen.audit.dfy(19,15): Warning: This declaration has explicit `{:axiom}` attribute.\n\nDafny auditor completed with 1 findings\n"
	// The generation's own axiom moves down when lines are added above it.
	written := strings.Replace(generated, "{\n}\n", "{\n  assume lo <= x;\n}\n", 1) + "\nlemma {:axiom} Helper()\n  ensures false\n"
	writtenOutput := "clamp.vibe.dfy(17,2): Warning: assume statement has no {:axiom} annotation\nclamp.vibe.dfy(20,15): Warning: This declaration has explicit `{:axiom}` attribute.\nclamp.vibe.dfy(23,15): Warning: This declaration has explicit `{:axiom}` attribute.\n"
	fromGenerated := dafnyAssumptions(generatedOutput, generated)
	if len(fromGenerated) != 1 || fromGenerated[0].member != "SplitAxiom" {
		t.Fatalf("the generation's findings: %+v", fromGenerated)
	}
	fromWritten := dafnyAssumptions(writtenOutput, written)
	if len(fromWritten) != 3 {
		t.Fatalf("the written file's findings: %+v", fromWritten)
	}
	if added := addedAssumptions(fromGenerated, fromGenerated); len(added) != 0 {
		t.Fatalf("a file adds to itself: %+v", added)
	}
	got := auditMessages(auditAssumptions("clamp.vibe", clamp.Functions, lemmaScriptInfo{}, fromWritten, fromGenerated))
	want := []string{
		"EK4318 clampInRange: clamp.vibe.dfy adds an assumption in the member clampInRange_ensures that dafny audit reports: assume statement has no {:axiom} annotation",
		"EK4318 <module>: clamp.vibe.dfy adds an assumption in the member Helper that dafny audit reports: This declaration has explicit `{:axiom}` attribute.",
	}
	if len(got) != len(want) {
		t.Fatalf("got %v", got)
	}
	for i := range want {
		if !strings.HasPrefix(got[i], want[i]) {
			t.Errorf("finding %d is %q, want the prefix %q", i, got[i], want[i])
		}
	}
	// The same finding twice in one member is an addition the second time.
	twice := append(append([]dafnyAssumption{}, fromGenerated...), fromGenerated...)
	if added := addedAssumptions(twice, fromGenerated); len(added) != 1 {
		t.Fatalf("a repeated finding: %+v", added)
	}
}

func TestCountObligations(t *testing.T) {
	lowered := "export function f(n: number): number {\n    //@ verify\n    //@ requires (n >= 0)\n    //@ ensures (\\result >= 0)\n    //@ ensures (\\result <= n)\n    while (n > 0) {\n        //@ invariant (n >= 0)\n        //@ decreases n\n        //@ assert (n > 0)\n        {}\n    }\n    return n; // not //@ assert in code\n}\n"
	if got := countObligations(lowered); got != 3 {
		t.Fatalf("got %d, want 3", got)
	}
}

// vibe.proofDir (Appendix F "Configuration"): a string, by default proofs in
// the selected config's directory. A relative path uses the declaring
// config's directory, a leading ${configDir} the selected config's, and a
// wrong type is EK3007.
func TestProofDirectoryConfiguration(t *testing.T) {
	parse := func(files map[string]any) (*tsoptions.ParsedCommandLine, []string) {
		var fs vfs.FS = bundled.WrapFS(vfstest.FromMap(files, tspath.CaseInsensitive))
		parsed, errors := tsoptions.GetParsedCommandLineOfConfigFile("/workspace/app/tsconfig.json", &core.CompilerOptions{}, nil, fs, nil)
		// The loader returns a config's errors, and the parsed config holds
		// them too: each counts once.
		var codes []string
		if parsed != nil {
			errors = append(errors, parsed.Errors...)
		}
		for _, d := range errors {
			if code := fmt.Sprintf("%s%d: %s", d.Source(), d.Code(), d.String()); !slices.Contains(codes, code) {
				codes = append(codes, code)
			}
		}
		return parsed, codes
	}
	for _, tc := range []struct {
		name  string
		files map[string]any
		want  string
	}{
		{"default", map[string]any{"/workspace/app/tsconfig.json": `{"files":["main.vibe"]}`}, "/workspace/app/proofs"},
		{"empty vibe", map[string]any{"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{}}`}, "/workspace/app/proofs"},
		{"relative", map[string]any{"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{"proofDir":"verification/dafny"}}`}, "/workspace/app/verification/dafny"},
		{"dot relative", map[string]any{"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{"proofDir":"./../shared/proofs"}}`}, "/workspace/shared/proofs"},
		{"absolute", map[string]any{"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{"proofDir":"/var/proofs"}}`}, "/var/proofs"},
		{"configDir", map[string]any{"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{"proofDir":"${configDir}/.proofs"}}`}, "/workspace/app/.proofs"},
		{"extended relative", map[string]any{
			"/workspace/app/tsconfig.json":  `{"extends":"../base/tsconfig.json","files":["main.vibe"]}`,
			"/workspace/base/tsconfig.json": `{"vibe":{"proofDir":"generated"}}`,
		}, "/workspace/base/generated"},
		{"extended configDir", map[string]any{
			"/workspace/app/tsconfig.json":  `{"extends":"../base/tsconfig.json","files":["main.vibe"]}`,
			"/workspace/base/tsconfig.json": `{"vibe":{"proofDir":"${configDir}/generated"}}`,
		}, "/workspace/app/generated"},
		{"overridden", map[string]any{
			"/workspace/app/tsconfig.json":  `{"extends":"../base/tsconfig.json","files":["main.vibe"],"vibe":{"proofDir":"mine"}}`,
			"/workspace/base/tsconfig.json": `{"vibe":{"proofDir":"generated"}}`,
		}, "/workspace/app/mine"},
		{"inherited beside other keys", map[string]any{
			"/workspace/app/tsconfig.json":  `{"extends":"../base/tsconfig.json","files":["main.vibe"],"vibe":{"effectGlobals":false}}`,
			"/workspace/base/tsconfig.json": `{"vibe":{"proofDir":"generated"}}`,
		}, "/workspace/base/generated"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			tc.files["/workspace/app/main.vibe"] = "export const one = 1\n"
			parsed, errors := parse(tc.files)
			if len(errors) != 0 {
				t.Fatalf("config: %v", errors)
			}
			if got := tspath.NormalizeSlashes(proofDirectoryOf(parsed.CompilerOptions(), "/workspace/app")); got != tc.want {
				t.Fatalf("got %s, want %s", got, tc.want)
			}
		})
	}
	for _, value := range []string{`3`, `true`, `null`, `["proofs"]`, `{}`, `""`} {
		t.Run("wrong type "+value, func(t *testing.T) {
			parsed, errors := parse(map[string]any{
				"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{"proofDir":` + value + `}}`,
				"/workspace/app/main.vibe":     "export const one = 1\n",
			})
			if len(errors) != 1 || !strings.HasPrefix(errors[0], "EK3007: ") || !strings.Contains(errors[0], "vibe.proofDir must be a path string") {
				t.Fatalf("got %v, want one EK3007", errors)
			}
			if parsed != nil && parsed.CompilerOptions().VibeLang != nil && parsed.CompilerOptions().VibeLang.ProofDir != "" {
				t.Fatalf("a wrong value set the proof directory to %q", parsed.CompilerOptions().VibeLang.ProofDir)
			}
		})
	}
	// An unknown key still names proofDir among the options.
	_, errors := parse(map[string]any{
		"/workspace/app/tsconfig.json": `{"files":["main.vibe"],"vibe":{"proofDirectory":"proofs"}}`,
		"/workspace/app/main.vibe":     "export const one = 1\n",
	})
	if len(errors) != 1 || !strings.Contains(errors[0], "Unknown vibe option proofDirectory") || !strings.Contains(errors[0], "proofDir") {
		t.Fatalf("got %v", errors)
	}
}
