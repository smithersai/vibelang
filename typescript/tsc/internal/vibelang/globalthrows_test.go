// globalThrowsFile is the generated table, relative to this package.
const globalThrowsFile = "globalthrows_table.go"

// TestGlobalThrowsTable generates globalThrowsTable from the ES lib files
// and globalThrowsCurated, and fails when the checked-in table differs. Run
// it with UPDATE_GLOBAL_THROWS=1 to rewrite the table.
func TestGlobalThrowsTable(t *testing.T) {
	keys, classes := libGlobalKeys(t)
	if len(keys) < 1000 {
		t.Fatalf("found %d lib members; the declaration walk is broken", len(keys))
	}
	var b strings.Builder
	b.WriteString("// Code generated by TestGlobalThrowsTable from globalThrowsCurated and the ES lib files. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with UPDATE_GLOBAL_THROWS=1 go test ./internal/vibelang -run TestGlobalThrowsTable.\n\n")
	b.WriteString("package vibelang\n\n")
	b.WriteString("// globalThrowsTable is the @throws annotation VibeLang ships for each member\n")
	b.WriteString("// of JavaScript's globals (VIP-4), by globalKey.\n")
	b.WriteString("var globalThrowsTable = map[string]string{\n")
	for _, key := range keys {
		throws, ok := curatedThrows(key)
		if !ok {
			throws = "never"
		}
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(key), strconv.Quote(throws))
	}
	b.WriteString("}\n")
	source, err := gofmt.Source([]byte(b.String()))
	if err != nil {
		t.Fatal(err)
	}
	want := string(source)
	if os.Getenv("UPDATE_GLOBAL_THROWS") == "1" {
		if err := os.WriteFile(globalThrowsFile, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(globalThrowsFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is out of date; regenerate it with UPDATE_GLOBAL_THROWS=1 go test ./internal/vibelang -run TestGlobalThrowsTable", globalThrowsFile)
	}
	for pattern, throws := range globalThrowsCurated {
		if !slices.ContainsFunc(keys, func(key string) bool { matched, _ := path.Match(pattern, key); return matched }) {
			t.Errorf("globalThrowsCurated lists %s, which names no member of the ES lib files", pattern)
		}
		if throws == globalThrowsUnknown {
			continue
		}
		for _, class := range strings.Split(throws, "|") {
			if class = strings.TrimSpace(class); class != "never" && !classes[class] {
				t.Errorf("%s throws %s, which is not a global error class", pattern, class)
			}
		}
	}
}

// TestGlobalThrows checks the annotations VIP-4 names.
func TestGlobalThrows(t *testing.T) {
	tests := []struct {
		key     string
		classes []string
		known   bool
	}{
		{"JSON.parse", []string{"SyntaxError"}, true},
		{"Math.max", nil, true},
		{"JSON.stringify", nil, true},
		{"String.toUpperCase", nil, true},
		{"BigIntConstructor()", []string{"SyntaxError", "RangeError"}, true},
		{"Intl.getCanonicalLocales", []string{"RangeError"}, true},
		{"eval", nil, false},
		{"TextEncoder.encode", nil, true},
		{"Headers.set", []string{"TypeError"}, true},
		{"AbortSignal.throwIfAborted", nil, false},
		{"fetch", nil, false}, // the DOM's: not annotated
	}
	for _, test := range tests {
		classes, known := globalThrowsOf(test.key)
		if !slices.Equal(classes, test.classes) || known != test.known {
			t.Errorf("globalThrowsOf(%q) = %v, %v; want %v, %v", test.key, classes, known, test.classes, test.known)
		}
	}
}

// libGlobalKeys returns the sorted keys of every signature the ES lib files
// declare, and of each signature of the DOM lib files that
// globalThrowsCurated names, and the names of the globals they declare
// with declare var.
func libGlobalKeys(t *testing.T) ([]string, map[string]bool) {
	t.Helper()
	dir := filepath.Join("..", "bundled", "libs")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	seen, vars := map[string]bool{}, map[string]bool{}
	for _, entry := range entries {
		name := entry.Name()
		es := strings.HasPrefix(name, "lib.es") || strings.HasPrefix(name, "lib.decorators")
		if !es && !strings.HasPrefix(name, "lib.dom") {
			continue
		}
		text, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		file := parseDeclarations("/lib/"+name, string(text))
		var visit func(node *ast.Node) bool
		visit = func(node *ast.Node) bool {
			switch node.Kind {
			case ast.KindFunctionDeclaration, ast.KindMethodSignature, ast.KindCallSignature, ast.KindFunctionType:
				if key := globalKey(node); key != "" {
					if _, curated := curatedThrows(key); es || curated {
						seen[key] = true
					}
				}
			case ast.KindVariableDeclaration:
				if name := declarationName(node); name != "" {
					vars[name] = true
				}
			}
			return node.ForEachChild(visit)
		}
		file.AsNode().ForEachChild(visit)
	}
	keys := make([]string, 0, len(seen))
	for key := range seen {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys, vars
}
