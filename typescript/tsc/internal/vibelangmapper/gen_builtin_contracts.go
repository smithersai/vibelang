//go:build ignore

// Generate the projector's built-in contracts from the @throws annotations
// VibeLang ships for JavaScript's globals (VIP-4), so adding a shipped
// annotation cannot create a second independent list. The projector names a
// call by its source chain and passes one failure class to $trusted, so it
// keeps each member that throws exactly one class and that source code calls
// by name: "JSON.parse", "Intl.NumberFormat.supportedLocalesOf". It drops
// constructor call signatures ("BigIntConstructor()"), unions, never and
// unknown.
//
// go run gen_builtin_contracts.go [-o output]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	output := flag.String("o", "builtin_contracts_generated.go", "the file to write")
	flag.Parse()
	fs := token.NewFileSet()
	f, err := parser.ParseFile(fs, "../vibelang/globalthrows_table.go", nil, 0)
	if err != nil {
		panic(err)
	}
	contracts := map[string]string{}
	found := false
	ast.Inspect(f, func(n ast.Node) bool {
		v, ok := n.(*ast.ValueSpec)
		if !ok || len(v.Names) != 1 || v.Names[0].Name != "globalThrowsTable" {
			return true
		}
		found = true
		for _, entry := range v.Values[0].(*ast.CompositeLit).Elts {
			kv := entry.(*ast.KeyValueExpr)
			key, err1 := strconv.Unquote(kv.Key.(*ast.BasicLit).Value)
			throws, err2 := strconv.Unquote(kv.Value.(*ast.BasicLit).Value)
			if err1 != nil || err2 != nil {
				panic(fmt.Sprint(err1, err2))
			}
			if throws == "never" || throws == "unknown" || strings.Contains(throws, "|") || strings.HasSuffix(key, "()") {
				continue
			}
			parts := strings.Split(key, ".")
			for i := range parts {
				parts[i] = strings.TrimSuffix(parts[i], "Constructor")
			}
			contracts[strings.Join(parts, ".")] = throws
		}
		return false
	})
	if !found {
		panic("missing globalThrowsTable")
	}
	keys := make([]string, 0, len(contracts))
	for key := range contracts {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out bytes.Buffer
	out.WriteString("// Code generated by gen_builtin_contracts.go from vibelang.globalThrowsTable (VIP-4); DO NOT EDIT.\n\npackage vibelangmapper\n\nvar builtinContracts = map[string]string{\n")
	for _, key := range keys {
		fmt.Fprintf(&out, "\t%q: %q,\n", key, contracts[key])
	}
	out.WriteString("}\n")
	data, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*output, data, 0644); err != nil {
		panic(err)
	}
}
