#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadSpec } from './spec-docs.mjs'
import { loadVips } from './vip-docs.mjs'

const [source, flag, factsFile, ...rest] = process.argv.slice(2)
if (!source || flag !== '--facts' || !factsFile || rest.length) {
  console.error('usage: node scripts/sync-spec-docs.mjs <repo>/docs --facts <file.json>')
  process.exit(2)
}
try {
  const spec = loadSpec(source)
  const facts = JSON.parse(fs.readFileSync(factsFile, 'utf8'))
  const converted = new Map(spec.chapters.map(file => [file.replace(/\.md$/, '.mdx'), spec.convert(file, facts)]))
  converted.set('index.mdx', converted.get('000-intro.mdx'))
  const docs = fileURLToPath(new URL('../', import.meta.url))
  const dest = path.join(docs, 'src/pages/spec')
  fs.mkdirSync(dest, { recursive: true })
  for (const file of fs.readdirSync(dest)) if (!converted.has(file)) fs.rmSync(path.join(dest, file), { recursive: true })
  for (const [file, body] of converted) fs.writeFileSync(path.join(dest, file), body)
  fs.writeFileSync(path.join(docs, 'spec-sidebar.ts'), `// Generated by scripts/sync-spec-docs.mjs. Do not edit.\nimport type { Config } from 'vocs/config'\n\nexport const specSidebar = ${JSON.stringify([spec.sidebar], null, 2)} satisfies Config['sidebar']\n`)
  // The improvement proposals (docs/design/vips) render beside the specification.
  const vips = loadVips(source)
  const vipDest = path.join(docs, 'src/pages/vips')
  fs.mkdirSync(vipDest, { recursive: true })
  for (const file of fs.readdirSync(vipDest)) if (!vips.pages.has(file)) fs.rmSync(path.join(vipDest, file), { recursive: true })
  for (const [file, body] of vips.pages) fs.writeFileSync(path.join(vipDest, file), body)
  fs.writeFileSync(path.join(docs, 'vips-sidebar.ts'), `// Generated by scripts/sync-spec-docs.mjs from docs/design/vips. Do not edit.\nimport type { Config } from 'vocs/config'\n\nexport const vipsSidebar = ${JSON.stringify([vips.sidebar], null, 2)} satisfies Config['sidebar']\n`)
  console.log(`sync-spec-docs: ${converted.size} pages; ${JSON.stringify(spec.counts())} (excluding duplicate index); ${vips.pages.size} VIP pages`)
} catch (error) {
  console.error(`sync-spec-docs: ${error.message}`)
  process.exitCode = 1
}
