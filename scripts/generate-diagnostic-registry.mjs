#!/usr/bin/env node
// The docs CLI regenerates this registry; docs checking and release tests verify --check.
// Keep compiler configuration independent of the checker package and its legacy codes.
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { spawnSync } from "node:child_process"

const root = new URL("../", import.meta.url)
const source = new URL("docs/design/src/900-appendices.md", root)
const target = new URL("typescript/tsc/internal/core/vibe_diagnostic_registry.go", root)
const text = readFileSync(source, "utf8")
const heading = "## Appendix B. Diagnostics\n"
const start = text.indexOf(heading)
if (start < 0) throw new Error("missing Appendix B. Diagnostics")
const appendix = text.slice(start + heading.length).split(/\n## /, 1)[0]
const rows = [...appendix.matchAll(/^\| `?(EK[0-9]{4,})`? \| (.*)/gm)]
if (!rows.length) throw new Error("Appendix B assigns no diagnostic codes")
const codes = new Set()
const entries = rows.map(([, code, rule]) => {
  if (codes.has(code)) throw new Error(`duplicate diagnostic code ${code}`)
  codes.add(code)
  const category = /^lint warning\b/.test(rule) ? "lint warning" : /^warning\b/.test(rule) ? "warning" : "error"
  return `\t${JSON.stringify(code)}: ${JSON.stringify(category)},`
})
const output = `// Code generated by scripts/generate-diagnostic-registry.mjs from docs/design/src/900-appendices.md; DO NOT EDIT.

package core

// VibeDiagnosticCategories records Appendix B's own diagnostic categories.
// Legacy checker messages are not part of this registry; imported lint codes
// are assigned separately in VibeImportedLintCodes.
var VibeDiagnosticCategories = map[string]string{
${entries.join("\n")}
}
`
const result = spawnSync("gofmt", [], {input: output, encoding: "utf8"})
if (result.error) throw result.error
if (result.status !== 0) throw new Error(result.stderr)
const formatted = result.stdout
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== formatted) throw new Error(`stale ${fileURLToPath(target)}; run node scripts/generate-diagnostic-registry.mjs`)
} else if (!existsSync(target) || readFileSync(target, "utf8") !== formatted) {
  writeFileSync(target, formatted)
}
