// Uses the same TypeScript 5.9.3 program/host as the resolution matrix.
import { matrix } from "./resolution-matrix.mjs"
import {readFileSync,writeFileSync} from "node:fs"
import {fileURLToPath} from "node:url"
export const declarationMatrix = () => matrix(true)
if (process.argv[1] === fileURLToPath(import.meta.url)) {
 const data=declarationMatrix()
 if(process.argv.includes("--json")) console.log(JSON.stringify(data))
 else {
  const tick=String.fromCharCode(96), code=s=>tick+String(s)+tick
  const md=["<!-- Generated by scripts/declaration-matrix.mjs; do not edit. -->","","# Declaration import spelling matrix","",
   "TypeScript "+code(data.typescript)+" runs the all-TypeScript twin in each cell with "+code("declaration")+" and "+code("emitDeclarationOnly")+". The shared resolution harness sets "+code("jsx: preserve")+" and both package types. Diagnostic codes are recorded even when output is emitted. Every declaration preserves the source specifier; "+code("rewriteRelativeImportExtensions")+" and "+code("allowImportingTsExtensions")+" do not change it.","",
   "Regenerate with "+code("node scripts/declaration-matrix.mjs --write")+"; check with "+code("node scripts/declaration-matrix.mjs --check")+". The compiler differential and keyed fuzz generator run this oracle again, rather than trusting this snapshot.","",
   "| Resolution | Allow | Rewrite | Package | TypeScript import → target | VibeLang import → target | tsc declaration import | Diagnostics |",
   "| --- | --- | --- | --- | --- | --- | --- | --- |"]
  for(const r of data.rows)md.push("| "+[r.resolution,r.allow,r.rewrite,r.packageType,r.nativeSpecifier+" → "+r.nativeTarget,r.vibeSpecifier+" → "+r.vibeTarget,r.emitted.join(", "),r.diagnostics.map(n=>"TS"+n).join(", ")||"—"].map(code).join(" | ")+" |")
  for(const [name,text]of [["declaration-matrix.json","{\n  \"typescript\": " + JSON.stringify(data.typescript) + ",\n  \"rows\": [\n" + data.rows.map(r => "    " + JSON.stringify(r)).join(",\n") + "\n  ]\n}\n"],["declaration-matrix.md",md.join("\n")+"\n"]]) {
   const path=new URL("../docs/design/"+name,import.meta.url)
   if(process.argv.includes("--write"))writeFileSync(path,text)
   else if(readFileSync(path,"utf8")!==text)throw new Error("Stale "+name)
  }
  console.log(data.rows.length+" declaration cells "+(process.argv.includes("--write")?"written":"checked"))
 }
}
