// Generated census format shared by the table writer and rule-evidence reader.
export const sourcePath = "docs/design/registry/grammar-admission.tsv"
export const outputs = [
  "typescript/tsc/internal/vibelangfuzz/testdata/grammar_admission.tsv",
  "docs/design/src/900-appendices.md"
]
export const marker = `Generated by scripts/generate-grammar-admission.mjs from ${sourcePath}; DO NOT EDIT.`
export const start = "<!-- grammar-admission:start -->"
export const end = "<!-- grammar-admission:end -->"
const code = text => {
  const fence = "`".repeat(Math.max(0, ...[...text.matchAll(/`+/g)].map(m => m[0].length)) + 1)
  return fence + " " + text.replaceAll("|", "\\|") + " " + fence
}

const censusTable = "| Hook | Form | Authority | Status | Reason |\n| --- | --- | --- | --- | --- |\n"
const censusFooter = "\n\n</details>\n\n" + end

export function censusSection(rows) {
  return start + "\n<!-- " + marker + " -->\n\n" +
    "### Grammar admission inventory\n\n" +
    "This implementation census records each parser or lowering hook and its specification authority. " +
    "It does not admit syntax: the productions and prose above remain the independent grammar oracle. " +
    "A `pending` row has no authority; `support` and `recovery` rows do not add language forms.\n\n" +
    "<details>\n<summary>Parser and lowering hooks (" + rows.length + " records)</summary>\n\n" +
    censusTable +
    rows.map(r => "| " + [code(r.hook), code(r.form),
      r.authority.split(",").map(ref => code(ref.trim())).join(", "), code(r.status),
      r.reason.replaceAll("|", "\\|")].join(" | ") + " |").join("\n") +
    censusFooter
}

// Evidence readers exempt only the exact generated frame and valid census
// rows. Arbitrary prose, forged markers and malformed records remain rules.
export function isGeneratedCensusSection(section) {
  const at = section.indexOf(censusTable)
  if (at < 0 || !section.endsWith(censusFooter)) return false
  const rowStart = at + censusTable.length
  const body = section.slice(rowStart, -censusFooter.length)
  if (!body) return false
  const rows = body.split("\n")
  const seen = new Set()
  const rowPattern = /^\| ` ((?:parser|vibelang)\/[\w]+\.go:[\w.]+(?:@[\w.-]+)?) ` \| ` admission:[\w.-]+ ` \| (` - `|` [\w-]+\.md(?:#[\w-]+)? `(?:, ` [\w-]+\.md(?:#[\w-]+)? `)*) \| ` (admitted|support|recovery|pending) ` \| (.+) \|$/
  for (const row of rows) {
    const match = rowPattern.exec(row)
    if (!match || seen.has(match[1])) return false
    seen.add(match[1])
    // The writer escapes every separator inside the reason cell.
    for (let i = 0; i < match[4].length; i++)
      if (match[4][i] === "|" && (i === 0 || match[4].charCodeAt(i - 1) !== 92)) return false
    if ((match[2] === "` - `") !== (match[3] === "pending")) return false
  }
  const frame = section.slice(0, rowStart) + section.slice(rowStart + body.length)
  return frame === censusSection([]).replace("(0 records)", "(" + rows.length + " records)")
}

