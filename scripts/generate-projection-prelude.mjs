// The experimental mapper owns the projection helpers. Ship the same types
// with the compiler so standalone projection consumers need no private package.
import { readFileSync, writeFileSync } from "node:fs"

const source = new URL("../packages/ts-mapper/prelude.d.ts", import.meta.url)
const target = new URL("../packages/compiler/prelude.d.ts", import.meta.url)
const header = "// Generated by scripts/generate-projection-prelude.mjs from packages/ts-mapper/prelude.d.ts. Do not edit.\n"
const text = header + readFileSync(source, "utf8").replaceAll("vibelang-ts-mapper", "vibelang")
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== text) {
    throw new Error("projection prelude is stale; run node scripts/generate-projection-prelude.mjs")
  }
} else {
  writeFileSync(target, text)
}
