// Run: bun docs/tools/token-counts.ts [--write | --check | --files path...]
// Counts the tokens an agent reads to write VibeLang: the skill, every docs page
// in sidebar order, and each cheat-sheet pair of Effect TypeScript and VibeLang.
// --write rewrites the generated part of the token counts page, --check exits 1
// when that page differs from what this script measures, and --files prints the
// count of each named file. Uses the package.json pin: js-tiktoken 1.0.21.
import { getEncoding } from "js-tiktoken"
import { readFileSync, writeFileSync } from "node:fs"
import { relative, resolve } from "node:path"
import { pageKeys, readSidebar, type Page } from "./sidebar"

export const TOKENIZER = "OpenAI o200k_base (js-tiktoken 1.0.21)"
const encoder = getEncoding("o200k_base")
// Exact text, nothing stripped. Special-token strings count as ordinary text.
export const count = (text: string) => encoder.encode(text, [], []).length

const repo = resolve(import.meta.dir, "../..")
export const SKILL = "packages/compiler/skills/vibelang/SKILL.md"
export const PAGE = "vibelang-features/117-token-counts.md"
const CHEAT_SHEET = "vibelang-features/115-cheat-sheet.md"
const BEGIN = "<!-- token-counts: generated by docs/tools/token-counts.ts --write -->"
const END = "<!-- token-counts: end -->"

// The docs checker's own lines inside a code block: they test the example and
// are not part of the program a reader writes.
// The docs' "Plain TypeScript … not VibeLang." comments annotate hatch and module bodies for readers;
// like the snippet directives, they are not program text, so they don't count.
const DIRECTIVE = /^\s*\/\/ (?:run:|Output:|expect-error:|fragment\b|compiler-gap:|pending:|pending-decision:|types:|.*\b[Pp]lain TypeScript\b.*\bnot VibeLang\.$)/
export const program = (code: string) => code.split("\n").filter(line => !DIRECTIVE.test(line)).join("\n")

export type Pair = { label: string; effect: string[]; vibe: string[] }

// A cheat-sheet entry is a bold label followed by code blocks. An entry pairs
// its ```ts effect blocks with its ```vibe blocks (```vibe long, VibeLang's long
// form, is neither side). Labels between two entries' blocks belong to the next
// entry, which takes the first of them.
export function cheatSheetPairs(markdown: string): Pair[] {
  const entries: Array<Pair & { long: number }> = []
  let current: (Pair & { long: number }) | undefined
  let labels: string[] = []
  let fence: { info: string; lines: string[] } | undefined
  const close = () => {
    if (current) entries.push(current)
    current = undefined
  }
  for (const line of markdown.split("\n")) {
    if (fence) {
      if (/^```\s*$/.test(line)) {
        const code = fence.lines.join("\n")
        const [lang, role] = fence.info.split(/\s+/)
        current ??= { label: labels[0] ?? "", effect: [], vibe: [], long: 0 }
        labels = []
        if (lang === "ts" && role === "effect") current.effect.push(code)
        else if (lang === "vibe" && role === "long") current.long++
        else if (lang === "vibe") current.vibe.push(code)
        fence = undefined
      } else fence.lines.push(line)
      continue
    }
    const open = /^```(\S.*)$/.exec(line)
    if (open) {
      fence = { info: open[1]!.trim(), lines: [] }
      continue
    }
    if (/^#{1,6} /.test(line)) {
      close()
      labels = []
      continue
    }
    const bold = /^\*\*(.+?)\*\*/.exec(line)
    if (bold) {
      close()
      labels.push(bold[1]!.trim().replace(/[.:]$/, "").replace(/\s*\(D\d+[^)]*\)$/, ""))
    }
  }
  close()
  return entries.filter(e => e.effect.length && e.vibe.length).map(({ label, effect, vibe }) => ({ label, effect, vibe }))
}

export function measurePairs(markdown: string) {
  const pairs = cheatSheetPairs(markdown).map(p => ({
    label: p.label,
    effect: p.effect.reduce((t, c) => t + count(program(c)), 0),
    vibe: p.vibe.reduce((t, c) => t + count(program(c)), 0)
  }))
  const effect = pairs.reduce((t, p) => t + p.effect, 0)
  const vibe = pairs.reduce((t, p) => t + p.vibe, 0)
  return { pairs, effect, vibe, longer: pairs.filter(p => p.vibe > p.effect).length,
    saving: (100 * (1 - vibe / effect)).toFixed(1) }
}

const percentFewer = (effect: number, vibe: number) => `${(100 * (1 - vibe / effect)).toFixed(1)}%`
const read = (path: string) => readFileSync(resolve(repo, path), "utf8")
const link = (from: string, to: string) => relative(resolve(from, ".."), to).replaceAll("\\", "/")

// The generated part of the page: what an agent loads, the cheat-sheet pairs,
// and every page in sidebar order. Links reach only docs pages, which the
// vibelang.sh sync (site/scripts/sync-user-docs.mjs) can resolve; repository
// files are named in code spans.
export function generate(): string {
  const { src, fileOf } = pageKeys(repo)
  const pagePath = resolve(src, PAGE)
  const { navigation, order } = readSidebar(read("docs/user/inventory.md"), repo)
  const pages = order.filter(p => p.path !== PAGE)
  const tokens = new Map(pages.map(p => [p.path, count(readFileSync(fileOf(p.path), "utf8"))]))
  const sum = (list: Page[]) => list.reduce((total, p) => total + tokens.get(p.path)!, 0)
  const guide = pages.filter(p => !p.path.startsWith("spec/"))
  const spec = pages.filter(p => p.path.startsWith("spec/"))
  const skill = count(read(SKILL))
  const cheat = tokens.get(CHEAT_SHEET)
  if (cheat === undefined) throw new Error(`token-counts: the sidebar has no ${CHEAT_SHEET}`)
  const decisions = count(read("docs/design/DECISIONS.md"))
  const out: string[] = []
  out.push(
    "## What an agent loads",
    "",
    "| Load | Tokens |",
    "| --- | ---: |",
    `| The VibeLang skill, \`${SKILL}\` | ${skill.toLocaleString("en-US")} |`,
    `| The skill and the [cheat sheet](${link(pagePath, fileOf(CHEAT_SHEET))}) | ${(skill + cheat).toLocaleString("en-US")} |`,
    `| The skill and the user guide (${guide.length} pages) | ${(skill + sum(guide)).toLocaleString("en-US")} |`,
    `| The user guide alone | ${sum(guide).toLocaleString("en-US")} |`,
    `| The specification (${spec.length} chapters) | ${sum(spec).toLocaleString("en-US")} |`,
    `| The decision log, \`docs/design/DECISIONS.md\` | ${decisions.toLocaleString("en-US")} |`,
    ""
  )
  const measured = measurePairs(readFileSync(fileOf(CHEAT_SHEET), "utf8"))
  const pairCounts = measured.pairs
  const effectTotal = measured.effect
  const vibeTotal = measured.vibe
  out.push(
    "## Effect TypeScript beside VibeLang",
    "",
    measured.saving + "% fewer tokens across " + pairCounts.length + " pairs in total; VibeLang is longer in " + measured.longer + " pairs. This is the saving over the combined source tokens, not the arithmetic mean of the percentages below.",
    "",
    `Each row is one [cheat sheet](${link(pagePath, fileOf(CHEAT_SHEET))}) entry: its Effect TypeScript blocks against its VibeLang blocks. A negative saving means the VibeLang snippet is longer.`,
    "",
    "| Entry | Effect TypeScript | VibeLang | Saved |",
    "| --- | ---: | ---: | ---: |",
    ...pairCounts.map(p => `| ${p.label} | ${p.effect} | ${p.vibe} | ${percentFewer(p.effect, p.vibe)} |`),
    `| **All ${pairCounts.length} entries** | **${effectTotal.toLocaleString("en-US")}** | **${vibeTotal.toLocaleString("en-US")}** | **${percentFewer(effectTotal, vibeTotal)}** |`,
    ""
  )
  // One table per sidebar view. A bold row gives a group's total; its pages follow.
  out.push("## Every page", "")
  let view: string | undefined
  let rows: string[] = []
  let viewPages: Page[] = []
  const flush = () => {
    if (view !== undefined && viewPages.length) {
      out.push(`### ${view}`, "", "| Page | Tokens |", "| --- | ---: |", ...rows)
      out.push(`| **All ${viewPages.length} pages** | **${sum(viewPages).toLocaleString("en-US")}** |`, "")
    }
    rows = []
    viewPages = []
  }
  for (const item of navigation) {
    if (item.kind === "view") {
      flush()
      view = item.label
    } else if (item.kind === "group") {
      const members = pages.filter(p => p.view === view && p.group === item.label)
      if (members.length) rows.push(`| **${item.label}** | **${sum(members).toLocaleString("en-US")}** |`)
    } else if (item.page.path !== PAGE) {
      viewPages.push(item.page)
      rows.push(`| [${item.page.label}](${link(pagePath, fileOf(item.page.path))}) | ${tokens.get(item.page.path)!.toLocaleString("en-US")} |`)
    }
  }
  flush()
  return out.join("\n").trimEnd()
}

function splice(page: string, generated: string): string {
  const start = page.indexOf(BEGIN)
  const end = page.indexOf(END)
  if (start < 0 || end < start) throw new Error(`token-counts: ${PAGE} lacks the ${BEGIN} and ${END} markers`)
  return `${page.slice(0, start + BEGIN.length)}\n\n${generated}\n\n${page.slice(end)}`
}

export function measuredClaims() {
  const measured = measurePairs(read("docs/user/src/" + CHEAT_SHEET))
  const heroVibe = count(read(".smithers/token-compare/users.vibe"))
  const heroEffect = count(read(".smithers/token-compare/users.ts"))
  const summary = measured.saving + "% fewer tokens across " + measured.pairs.length + " cheat-sheet pairs; VibeLang is longer in " + measured.longer + " pairs."
  return {
    "README.md": "**" + summary + "** The example above uses **" + heroVibe + " vs " + heroEffect + " tokens (" + percentFewer(heroEffect, heroVibe) + " fewer)**.",
    "site/src/pages/index.mdx": "- **People can review what agents write.** [" + measured.saving + "% fewer tokens across the " + measured.pairs.length + " cheat-sheet pairs](/vibelang-features/117-token-counts); VibeLang is longer in " + measured.longer + " pairs."
  }
}

function updateClaims(write: boolean): boolean {
  let fresh = true
  for (const [path, claim] of Object.entries(measuredClaims())) {
    const current = read(path)
    const marker = /(?:<!-- token-headline:start -->|\{\/\* token-headline:start \*\/\})[\s\S]*?(?:<!-- token-headline:end -->|\{\/\* token-headline:end \*\/\})/
    if (!marker.test(current)) throw new Error(path + ": missing token-headline markers")
    const next = current.replace(marker, () => path.endsWith(".mdx")
      ? "{/* token-headline:start */}\n\n" + claim + "\n\n{/* token-headline:end */}"
      : "<!-- token-headline:start -->\n\n" + claim + "\n\n<!-- token-headline:end -->")
    if (next !== current) {
      fresh = false
      if (write) writeFileSync(resolve(repo, path), next)
      else console.error("token-counts: stale claim in " + path)
    }
  }
  return fresh
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  const { src } = pageKeys(repo)
  const pagePath = resolve(src, PAGE)
  if (args[0] === "--files") {
    for (const path of args.slice(1)) console.log(`${count(readFileSync(path, "utf8"))}\t${path}`)
  } else if (args[0] === "--write") {
    updateClaims(true)
    writeFileSync(pagePath, splice(readFileSync(pagePath, "utf8"), generate()))
    console.log(`token-counts: wrote ${relative(repo, pagePath)} (${TOKENIZER})`)
  } else if (args[0] === "--check" || args.length === 0) {
    const page = readFileSync(pagePath, "utf8")
    const claimsFresh = updateClaims(false)
    if (splice(page, generate()) !== page || !claimsFresh) {
      console.error(`token-counts: ${relative(repo, pagePath)} differs from the measured counts; run bun docs/tools/token-counts.ts --write`)
      process.exit(1)
    }
    console.log(`token-counts: ${relative(repo, pagePath)} matches the measured counts (${TOKENIZER})`)
  } else {
    console.error("usage: bun docs/tools/token-counts.ts [--write | --check | --files path...]")
    process.exit(2)
  }
}
