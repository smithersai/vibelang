import { describe, expect, test } from "bun:test"
import { readFileSync, mkdirSync, mkdtempSync, writeFileSync, rmSync } from "node:fs"
import { spawnSync } from "node:child_process"
import { join } from "node:path"
import fc from "fast-check"
import { vipRegistryFromSources } from "./spec-rules.mjs"
import { exclusions, parseCSV, census, normalize, parseSnapshot, reports, rules, totals, type Sources } from "./coverage-census"

const chapter = "docs/design/src/001-functions.md"
const vip = "docs/design/vips/0001-functions.md"
const fixture = (text: string): Sources => new Map([[chapter, "# Functions\n\n" + text + "\n"]])
const witness = "typescript/vibelang/cases/quoted/main.vibe"
const quote = "An `effect` function must return an Effect."
describe("source coverage census", () => {
  test("registered as a Smithers Run, with an independent regression target", () => {
    const source = readFileSync(process.env.CENSUS_PACKAGE_FIXTURE ?? new URL("../../PACKAGE.ts", import.meta.url), "utf8")
    expect(source).toContain('"spec-coverage-census": S.Shell.Run(')
    expect(source).toContain('"spec-coverage-census-test": S.Shell.Test(')
  })
  test("accepted status, fences, headings and generated sources", () => {
    const sources = fixture(quote + "\n\n```vibe\n// must be excluded\n```\n")
    sources.set(vip, "**Status:** accepted\n\n" + quote)
    sources.set(vip.replace("0001", "0002"), "**Status:** open\n\n" + quote)
    sources.set("docs/design/src/generated.md", "<!-- Generated by tool -->\n" + quote)
    const extracted = rules(sources)
    expect(extracted.length).toBe(2)
    expect(extracted[0].line).toBe(3)
    expect(extracted[0].id).not.toBe(extracted[1].id)
  })
  test("identical repeats deduplicate within a file; wording changes get a new id", () => {
    const a = rules(fixture(quote))[0]
    expect(rules(fixture(quote + "\n\n" + quote)).length).toBe(1)
    expect(rules(fixture("Intro.\n\n" + quote))[0].id).toBe(a.id)
    expect(rules(fixture(quote.replace("must", "must never")))[0].id).not.toBe(a.id)
  })
  test("exact escaped oracle quotes count, a fragment does not", async () => {
    const sources = fixture(quote)
    sources.set("typescript/tsc/internal/vibelangfuzz/example_test.go", 'package x\nconst quote = ' + JSON.stringify(quote) + '\nfunc TestQuote(t *testing.T) {}')
    expect(totals(await census(sources)).covered).toBe(1)
    sources.set("typescript/tsc/internal/vibelangfuzz/example_test.go", 'func TestQuote(t *testing.T) {}\nconst quote = "must return an Effect"')
    expect(totals(await census(sources)).covered).toBe(0)
  })
  test("a diagnostic or shared code is only a candidate, never coverage", async () => {
    const sources = fixture("`try x` must run an Effect; otherwise it is `EK0502`.")
    sources.set(witness, "// expect: EK0502\neffect function main() { return try 1 }")
    const rows = await census(sources)
    expect(rows[0].evidence[0].low).toBe(true)
    expect(totals(rows).covered).toBe(0)
    expect(reports(rows, "abc", "disabled").csv).toContain('"yes","shared-code"')
  })
  test("an explicit stable id counts; a chapter heading reference does not", async () => {
    const sources = fixture(quote), id = rules(sources)[0].id
    sources.set(witness, "// rule-evidence: " + chapter + "#functions")
    expect(totals(await census(sources)).covered).toBe(0)
    sources.set(witness, "// rule-evidence: " + id + "\neffect function load() { return 1 }")
    expect(totals(await census(sources)).covered).toBe(1)
  })
  test("expected generated output and testdata are excluded", async () => {
    const sources = fixture(quote)
    sources.set("typescript/vibelang/cases/sample/expected/main.d.ts", "// " + quote)
    sources.set("typescript/tsc/internal/vibelangfuzz/testdata/a_test.go", 'func TestA(t *testing.T) {}\n// ' + quote)
    expect(totals(await census(sources)).covered).toBe(0)
  })
  test("a harness pending marker classifies its case as pending", async () => {
    const sources = fixture(quote)
    sources.set(witness, "// " + quote)
    expect(totals(await census(sources)).covered).toBe(1)
    sources.set(witness.replace("main.vibe", "pending"), "compiler gap")
    expect(totals(await census(sources)).pending).toBe(1)
  })
  test("framed snapshot preserves paths, content and missing final newline", () => {
    expect(parseSnapshot("\0a b\0first\n+second").get("a b")).toBe("first\n+second")
    expect(parseSnapshot("\0a\0x\n\0b\0y").get("b")).toBe("y")
    expect(() => parseSnapshot("unframed")).toThrow("Malformed")
    expect(() => parseSnapshot("\0a\0x\0a\0y")).toThrow("duplicate")
  })
  test("adjacent twins count only after successful compilation and cache a shared pair", async () => {
    const text = "An `effect function` must return an Effect.\nThe `effect function` compiles to Effect.gen.\n\n" +
      "```vibe\nexport effect function value() { return 1 }\n```\n\n" +
      "```ts effect\nexport function value() { return Effect.succeed(1) }\n```\n"
    const sources = fixture(text)
    expect(totals(await census(sources)).covered).toBe(0)
    let calls = 0
    const rows = await census(sources, async () => { calls++; return { ok: true, reason: "verified declarations" } })
    expect(calls).toBe(1)
    expect(totals(rows).covered).toBe(2)
    expect(totals(await census(sources, async () => ({ ok: false, reason: "different declarations" }))).covered).toBe(0)
  })
  test("CSV quotes commas, quotes, and line breaks; chapters are grouped", async () => {
    const sources = fixture('The `"hello, world"` form must compile.')
    sources.set(vip, "**Status:** accepted\n\n" + quote)
    const rows = await census(sources), out = reports(rows, "immutable", "disabled")
    expect(out.csv).toStartWith('"rule","test","missing",')
    expect(out.csv).toContain('""hello, world""')
    expect(out.markdown).toContain("## " + chapter)
    expect(out.percent).toBe("passing 0, pending 0, no test 2 of 2 rules (excluded 0)\n")
    expect(totals([]).percent).toBe("0.00")
  })
  test("accepted VIP parser rejects missing status and shares the linter contract", () => {
    expect(() => vipRegistryFromSources(new Map([[vip, quote]]))).toThrow("missing VIP status")
    const registry = vipRegistryFromSources(new Map([[vip, "**Status:** accepted\n" + quote]]))
    expect(registry.get(1).status).toBe("accepted")
  })
  test("watcher checks once, reruns changed main and preserves outputs on collection failure", () => {
    const base = process.env.CENSUS_TEST_TMPDIR ?? join(import.meta.dir, "../../.cache")
    mkdirSync(base, { recursive: true })
    const dir = mkdtempSync(join(base, "census-watch-")), bin = join(dir, "bin"), out = join(dir, "out")
    mkdirSync(bin); mkdirSync(out)
    writeFileSync(join(bin, "jj"), '#!/bin/bash\nif [ "$1" = git ]; then exit 0; fi\necho aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\n', { mode: 0o755 })
    writeFileSync(join(bin, "bun"), '#!/bin/bash\necho run >> "$CENSUS_STATE/calls"\nexit 1\n', { mode: 0o755 })
    writeFileSync(join(out, "PERCENT"), "previous receipt")
    const run = () => spawnSync("bash", ["scripts/coverage-census-watch.sh"], {
      cwd: new URL("../../", import.meta.url), encoding: "utf8",
      env: { ...process.env, PATH: bin + ":" + process.env.PATH, CENSUS_OUT: out, CENSUS_STATE: join(dir, "state"), CENSUS_ONCE: "1", CENSUS_SMTHRS: join(bin, "bun") }
    })
    try {
      expect(run().status).toBe(0)
      expect(readFileSync(join(out, "PERCENT"), "utf8")).toBe("previous receipt")
      expect(readFileSync(join(dir, "state/history.log"), "utf8")).toContain("census failed")
      writeFileSync(join(out, "REVISION"), "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\n")
      expect(run().status).toBe(0)
      expect(readFileSync(join(dir, "state/calls"), "utf8")).toBe("run\nrun\n")
      expect(readFileSync(join(dir, "state/LAST_CHECK"), "utf8")).toContain("checked aaaa")
    } finally { rmSync(dir, { recursive: true, force: true }) }
  })
  test("seeded mutations preserve IDs across blank lines and wrapping, but code changes do not", () => {
    fc.assert(fc.property(fc.integer({ min: 0, max: 20 }), fc.integer({ min: 1, max: 20 }), (blank, n) => {
      const text = "The `value" + n + "` form must compile."
      const id = rules(fixture(text))[0].id
      expect(rules(fixture("\n".repeat(blank) + text.replace(" must ", "\n must ")))[0].id).toBe(id)
      expect(rules(fixture(text.replace("value" + n, "other" + n)))[0].id).not.toBe(id)
      expect(normalize(text.replace(" must ", "\n must "))).toBe(text)
    }), { seed: 20261103, numRuns: 150 })
  })
})

describe("three-way census", () => {
  test("pending cases retain quoted evidence and do not count as passing", async () => {
    const sources = fixture(quote)
    sources.set(witness, "// " + quote)
    sources.set(witness.replace("main.vibe", "pending"), "waiting")
    const rows = await census(sources)
    expect(totals(rows).pending).toBe(1)
    expect(totals(rows).passing).toBe(0)
    expect(reports(rows, "a", "off").csv).toContain('"pending"')
  })
  test("Go skips and Vitest todo link only their own rule; passing takes precedence", async () => {
    const sources = fixture(quote + "\n\nThe `async` form must return a Promise.")
    sources.set("typescript/tsc/internal/vibelang/test_pending_test.go", 'package x\nfunc TestPending(t *testing.T) { t.Skip(' + JSON.stringify(quote) + ') }')
    sources.set("packages/runtime/tests/rules.test.ts", 'import { test } from "vitest";\ntest.todo("The `async` form must return a Promise.")')
    expect(totals(await census(sources)).pending).toBe(2)
    sources.set(witness, "// " + quote)
    const t = totals(await census(sources))
    expect(t.passing).toBe(1)
    expect(t.pending).toBe(1)
    expect(t.none).toBe(0)
  })
  test("chapter plus short rule name survives rewording; chapter alone does not", async () => {
    const sources = fixture("An `effect` function must return its unrun Effect.")
    sources.set(witness, "// Chapter 1: effect function")
    let rows = await census(sources)
    expect(totals(rows).tagLinked).toBe(1)
    expect(rows[0].evidence[0].kind).toBe("tag-linked")
    sources.set(witness, "// Chapter 1")
    expect(totals(await census(sources)).covered).toBe(0)
    sources.set(witness, "// Chapter 2: effect function")
    expect(totals(await census(sources)).covered).toBe(0)
  })
  test("exclusions remove rows from denominator and list the excluded count", async () => {
    const sources = fixture(quote), id = rules(sources)[0].id
    const rows = await census(sources, undefined, new Set([id]))
    expect(rows).toHaveLength(0)
    const out = reports(rows, "a", "off", 1)
    expect(out.percent).toBe("passing 0, pending 0, no test 0 of 0 rules (excluded 1)\n")
  })
})

test("exclusion CSV handles quoted commas, multiline reasons, duplicates and stale ids", () => {
  const base = process.env.CENSUS_TEST_TMPDIR ?? join(import.meta.dir, "../../.cache")
  mkdirSync(base, { recursive: true })
  const dir = mkdtempSync(join(base, "census-exclusions-"))
  try {
    writeFileSync(join(dir, "a.csv"), 'rule,reason\r\nabc,"reason, with\nnewline"\r\nabc,duplicate\nold,stale')
    expect([...exclusions(dir)]).toEqual(["abc", "old"])
    expect(parseCSV('rule,reason\nabc,"a ""quote"""')[1][1]).toBe('a "quote"')
    expect(() => parseCSV('rule,"broken')).toThrow("Unclosed")
    writeFileSync(join(dir, "bad.csv"), "id,reason\nx,y")
    expect(() => exclusions(dir)).toThrow("rule column")
  } finally { rmSync(dir, { recursive: true, force: true }) }
})

test("Vitest sibling declarations and comments inside strings do not leak pending evidence", async () => {
  const sources = fixture(quote + "\n\nThe `async` form must return a Promise.")
  sources.set("packages/runtime/tests/mixed.test.ts",
    'import { test } from "vitest";\ntest.todo(' + JSON.stringify(quote) +
    ');\ntest("The `async` form must return a Promise.", () => { const example = "test.todo(fake)"; });')
  const t = totals(await census(sources))
  expect(t.passing).toBe(1)
  expect(t.pending).toBe(1)
})
