test("r7 ASTRA-4: a removed catch guest example fails even inside schematic code", () => {
  const example = examples("```ts\neffect function f() { const g = fetchUser(id) catch guest }\n```\n")[0]
  const result = { status: 1, stdout: "main.vibe(1,50): error EK0509: A catch handler must be a function literal.\n", stderr: "" }
  assert.ok(verdict(example, result).some(f => f.severity === "error" && f.message.includes("EK0509")))
  assert.ok(verdict({ ...example, schematic: true }, result).some(f => f.severity === "error"))
})
test("handler tokenization preserves native bare arrows, comments, strings and property names", () => {
  for (const source of ['const s = "catch guest"', 'effect { e catch x => x }', 'x.catch(handler)', '/* catch guest */ 1', 'try {} catch (e) {}'])
    assert.deepEqual(removedHandlers(source), [])
})
test("negative VIP examples require their stated code, and reject unexpected codes", () => {
  const example = examples("```vibe\n// expect-error: EK0509\neffect function f() { return fail(1) catch guest }\n```\n")[0]
  assert.equal(verdict(example, { status: 1, stdout: "main.vibe(2,1): error EK0509: handler\n" }).length, 0)
  assert.ok(verdict(example, { status: 0, stdout: "" }).some(f => f.message.includes("expected EK0509")))
  assert.ok(verdict(example, { status: 1, stdout: "main.vibe(2,1): error EK0401: other\n" }).some(f => f.severity === "error"))
  assert.throws(() => verdict(example, { status: 1, stdout: "compiler crashed" }), /without source diagnostics/)
})
