// Entry-scoped, deterministic evidence check. Semantic review belongs to rule-judge.
import { spawnSync } from "node:child_process"
import ts from "typescript"
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"
import { command, defaultCompiler, extract, linkModules, type Block } from "./check-snippets"

export type Change = { path: string; before: string; after: string }
export type Sentence = { path: string; line: number; text: string; section: string; removed?: boolean }
export type Finding = Sentence & { missing: string }
export type Entry = { base: string; head: string; changes: Change[] }
export type Twin = { vibe: Block; effect: Block }
export type TwinResult = { ok: boolean; reason: string }
const repo = resolve(import.meta.dir, "../..")
const specPath = (path: string) => /^docs\/design\/(?:src|vips)\/.*\.md$/.test(path)
const pendingPath = (path: string) => /^docs\/tools\/[^/]+\.test\.(?:ts|mjs)$/.test(path)
const casePath = (path: string) => /^typescript\/vibelang\/cases\/[^/]+\//.test(path)
const generated = (text: string) => /^\s*<!--[^>]*(?:generated by|automatically generated|auto-generated|do not edit)[^>]*-->/i.test(text)
const slug = (text: string) => text.toLowerCase().replace(/\x60/g, "").replace(/[^\p{L}\p{N}_ -]/gu, "").trim().replace(/\s+/g, "-")

// Backticks are protected: changing a literal, identifier or operator is never
// a spelling exemption. Normalize only presentation and a small closed typo list.
export function canonical(text: string): string {
  const parts = text.split(/(`+[^`]*`+)/g)
  const cited = parts.map((part, i) => i % 2
    ? /\beffect\s+$/i.test(parts[i - 1]) && /^(`+)\d+\.\d+\.\d+\1$/.test(part) ? "<version>" : part
    : part.replace(/\b(effect\s+)\d+\.\d+\.\d+/gi, "$1<version>")).join("")
  return cited
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\s*\((?:(?:decided )?details? \d+[a-z]?(?:[ ,and–-]+\d+[a-z]?)*|VIP-\d+(?:, amended)?)\)/gi, "").split(/(`+[^`]*`+)/g).map((part, i) =>
    i % 2 ? part : part.replace(/[*_]/g, "").replace(/\b(teh|thier|occurrs|recieve|sentance)\b/gi, word =>
      ({ teh: "the", thier: "their", occurrs: "occurs", recieve: "receive", sentance: "sentence" })[word.toLowerCase()]!).toLowerCase()
  ).join("").replace(/\s+/g, " ").replace(/[.!?]+$/, "").trim()
}

export function sentences(path: string, markdown: string): Sentence[] {
  if (generated(markdown)) return []
  const out: Sentence[] = []
  const lines = markdown.split(/\r?\n/)
  let fence = "", section = "", paragraph: { text: string; line: number }[] = [], comment = false
  const flush = () => {
    if (!paragraph.length) return
    const joined = paragraph.map(p => p.text).join("\n")
    // Split outside inline code. Dots inside a code span, e.g. `Effect.fail`,
    // and source line wrapping do not create sentences.
    let start = 0, ticks = 0
    for (let i = 0; i <= joined.length; i++) {
      if (joined[i] === "`") {
        let n = 1
        while (joined[i + n] === "`") n++
        ticks = ticks === n ? 0 : ticks || n
        i += n - 1
      }
      if (i === joined.length || (!ticks && /[.!?]/.test(joined[i]) && /\s/.test(joined[i + 1] ?? ""))) {
        const end = i === joined.length ? i : i + 1
        const part = joined.slice(start, end)
        const textStart = start + Math.max(0, part.search(/\S/))
        if (part.trim()) out.push({ path, line: paragraph[0].line + joined.slice(0, textStart).split("\n").length - 1,
          text: part.trim().replace(/\s+/g, " "), section })
        start = end
      }
    }
    paragraph = []
  }
  for (const [i, raw] of lines.entries()) {
    let original = raw
    const f = /^\s{0,3}(`{3,}|~{3,})/.exec(original)
    if (fence) {
      if (new RegExp("^\\s{0,3}" + fence[0] + "{" + fence.length + ",}\\s*$").test(original)) fence = ""
      continue
    }
    if (comment) {
      const close = original.indexOf("-->")
      if (close < 0) continue
      original = original.slice(close + 3); comment = false
    }
    while (original.includes("<!--")) {
      const start = original.indexOf("<!--"), end = original.indexOf("-->", start + 4)
      if (end < 0) { original = original.slice(0, start); comment = true; break }
      original = original.slice(0, start) + original.slice(end + 3)
    }
    if (f && original === raw) { flush(); fence = f[1]; continue }
    const heading = /^#{1,6}\s+(.+)$/.exec(original)
    if (heading) { flush(); section = slug(heading[1]); continue }
    if (!original.trim() || /^\s*(?:\[[^\]]+\]:|---+$|\|?\s*:?-+:?\s*\|)/.test(original)) { flush(); continue }
    // Lists and table rows are independent rules rather than one huge paragraph.
    if (/^\s*(?:[-*+] |\d+\. |\|)/.test(original)) flush()
    paragraph.push({ text: original.replace(/^\s*(?:[-*+] |\d+\. )/, ""), line: i + 1 })
    if (/^\s*\|/.test(original)) flush()
  }
  flush()
  return out
}

export function normative(text: string): boolean {
  if (/^`EK\d+` to `EK\d+` keep their specific triggers\.$/.test(text)) return false
  return /`[^`]+`|\b(?:EK|TS)\d{4,}\b|\b(?:must|compiles?|means)\b|\bis an? error\b/i.test(text)
}

export function changedRules(changes: Change[]): Sentence[] {
  const docs = changes.filter(c => specPath(c.path))
  // Compare the whole entry, so moving a rule to another chapter is exempt.
  const old = docs.flatMap(c => sentences(c.path, c.before))
  const next = docs.flatMap(c => sentences(c.path, c.after))
  const unmatched = (a: Sentence[], b: Sentence[]) => {
    const existing = new Set(b.map(s => canonical(s.text)))
    // Copying a published rule into its VIP or another chapter changes its
    // location/authority citation, not what the rule says.
    return a.filter(s => !existing.has(canonical(s.text)) && normative(s.text))
  }
  const added = unmatched(next, old)
  // Removed rules change the language too; do not let deleting a prohibition
  // bypass the gate. Replacement sentences are reported once, on the new side.
  const removed = unmatched(old, next).filter(s => !added.some(n =>
    n.path === s.path && n.section === s.section &&
    (anchors(s.text).some(key => anchors(n.text).includes(key)) ||
      canonical(s.text).replace(/`+[^`]*`+/g, "<code>") === canonical(n.text).replace(/`+[^`]*`+/g, "<code>"))))
  return [...added, ...removed.map(s => ({ ...s, removed: true }))]
}

const keywords = new Set(["effect", "async", "await", "try", "catch", "throw", "error", "schema", "data", "service",
  "match", "when", "is", "fork", "join", "provide", "uninterruptible", "interruptible", "restore", "return", "yield",
  "concurrent", "using", "do", "break", "continue"])
export function anchors(text: string): string[] {
  const codes = [...text.matchAll(/\b(?:EK|TS)\d{4,}\b/g)].map(m => m[0])
  if (codes.length) return [...new Set(codes)]
  const spans = [...text.matchAll(/`+([^`]+)`+/g)].map(m => m[1])
  const words = spans.flatMap(s => s.match(/[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*/g) ?? [])
  const grammar: Record<string, string> = { CatchExpression: "catch", ArrowHandler: "=>", PipeExpression: "|>",
    PipeBody: "|>", EffectArrow: "effect", MatchExpression: "match", MatchPattern: "when", VariableStatement: "var",
    ProvideStatement: "provide", ErrorDeclaration: "error", ServiceDeclaration: "service", SchemaDeclaration: "schema" }
  const aliases: Record<string, string> = { "Context.Service": "service", "Context.Reference": "service",
    "Data.TaggedError": "error", "Schema.TaggedError": "error", "Schema.Struct": "schema" }
  const specific = words.filter(w => w.length > 1).flatMap(w =>
    Object.hasOwn(grammar, w) ? [grammar[w]] :
      [w, ...(w.includes(".") ? [w.split(".").at(-1)!] : []), ...(Object.hasOwn(aliases, w) ? [aliases[w]] : [])])
  const operators = spans.flatMap(s => s.match(/!!|=>|\|>/g) ?? [])
  return [...new Set([...specific, ...operators])]
}

function sourceBody(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, comment => (comment.match(/@(?:internal|public|deprecated|throws)\b[^\n*]*/g) ?? []).join("\n")).replace(/^\s*\/\/(?!\s*expect(?:-result)?:).*$/gm, "").trim()
}
function exercises(rule: Sentence, body: string): boolean {
  const keys = anchors(rule.text)
  return keys.length > 0 && keys.some(key => {
    if (key === "for") return /\bfor\s*\([^)]*\bof\b/.test(body)
    return body.includes(key)
  })
}
function caseEvidence(rule: Sentence, changes: Change[]): string | undefined {
  const cases = changes.filter(c => casePath(c.path) && c.after)
  for (const c of cases) {
    if (c.path.endsWith("/package.json") && rule.text.includes("`effect/package.json`")) {
      try {
        const version = JSON.parse(c.after).dependencies?.effect
        const previous = c.before ? JSON.parse(c.before).dependencies?.effect : undefined
        if (typeof version === "string" && version !== previous && rule.text.includes("`" + version + "`")) return c.path
      } catch { /* Invalid case manifests do not establish a version witness. */ }
    }
    if (!/\.(?:vibe|vibex|ts|tsx|mjs|json|txt)$/.test(c.path) || /\/(?:out|node_modules)\//.test(c.path) || c.path.endsWith("/package.json")) continue
    if (sourceBody(c.before) === sourceBody(c.after)) continue
    const cited = [...c.after.matchAll(/^\s*\/\/[^\n]*\bVIP-(\d+)\b/gm)].map(m => Number(m[1]))
    const ownVip = /\/vips\/0*(\d+)[^/]*\.md$/.exec(rule.path)
    const codes = [...rule.text.matchAll(/\b(?:EK|TS)\d{4,}\b/g)].map(m => m[0])
    const peers = changes.filter(d => /\/vips\/\d+[^/]*\.md$/.test(d.path) && codes.some(code => d.after.includes(code)))
    const attributed = ownVip ? cited.includes(Number(ownVip[1])) :
      peers.some(d => cited.includes(Number(/\/vips\/0*(\d+)/.exec(d.path)![1])))
    if (attributed) return c.path
    // A diagnostic expectation is executable evidence too, even when it is
    // the changed line and the minimized input already existed.
    const reference = rule.path + (rule.section ? "#" + rule.section : "")
    const explicit = c.after.split("\n").some(line => /^\s*\/\/ rule-evidence: /.test(line) &&
      line.slice(line.indexOf(":") + 1).trim().split(/\s+/).includes(reference))
    if (explicit || exercises(rule, sourceBody(c.after)) || (rule.removed && exercises(rule, sourceBody(c.before)))) return c.path
  }
}

// Will, 2026-11-03: every unimplemented rule may have an explicit test.todo.
// These are pending obligations, never executable cases or compiled twins.
const pendingKey = (path: string, section: string, removed: boolean, text: string) =>
  JSON.stringify([path, section, removed, canonical(text)])

function pendingWitnesses(source: string): Set<string> {
  const file = ts.createSourceFile("witness.test.ts", source, ts.ScriptTarget.Latest, true)
  const tests = new Set<string>(), witnesses = new Set<string>()
  for (const statement of file.statements) {
    if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier) ||
      !["bun:test", "node:test"].includes(statement.moduleSpecifier.text) || statement.importClause?.isTypeOnly) continue
    const bindings = statement.importClause?.namedBindings
    if (bindings && ts.isNamedImports(bindings)) for (const item of bindings.elements) {
      if (!item.isTypeOnly && ["test", "it"].includes((item.propertyName ?? item.name).text)) tests.add(item.name.text)
    }
  }
  // Only top-level call statements qualify: a fixture string, comment, skipped
  // suite or uncalled function cannot manufacture a pending test.
  for (const statement of file.statements) {
    if (!ts.isExpressionStatement(statement) || !ts.isCallExpression(statement.expression)) continue
    const call = statement.expression, target = call.expression
    if (!ts.isPropertyAccessExpression(target) || target.name.text !== "todo" ||
      !ts.isIdentifier(target.expression) || !tests.has(target.expression.text) || call.arguments.length !== 1) continue
    const title = call.arguments[0]
    if (!ts.isStringLiteralLike(title)) continue
    const match = /^rule-evidence: (\S+) \| ([^|\n]+) \| (present|removed) \| ([\s\S]+)$/.exec(title.text)
    if (!match || !match[2].trim()) continue
    const [path, section = ""] = match[1].split("#")
    if (!specPath(path) || match[1].split("#").length > 2) continue
    witnesses.add(pendingKey(path, section, match[3] === "removed", match[4]))
  }
  return witnesses
}

function pendingEvidence(rule: Sentence, changes: Change[]): boolean {
  const key = pendingKey(rule.path, rule.section, !!rule.removed, rule.text)
  return changes.some(change => pendingPath(change.path) && change.after &&
    pendingWitnesses(change.after).has(key) && !pendingWitnesses(change.before).has(key))
}

export function nearbyTwins(rule: Sentence, markdown: string): Twin[] {
  if (rule.removed) return []
  const lines = markdown.split(/\r?\n/)
  const blocks: Block[] = []
  // Old VIPs contain mislabeled examples. An invalid unrelated fence cannot
  // turn an entry's missing-evidence verdict into a setup failure.
  for (let i = 0; i < lines.length; i++) {
    const fence = /^\s{0,3}(`{3,}|~{3,})/.exec(lines[i])
    if (!fence) continue
    const start = i
    const close = new RegExp("^\\s{0,3}" + fence[1][0] + "{" + fence[1].length + ",}\\s*$")
    while (++i < lines.length && !close.test(lines[i])) {}
    try {
      for (const block of extract(lines.slice(start, i + 1).join("\n"))) blocks.push({
        ...block, number: blocks.length + 1, line: block.line + start, endLine: (block.endLine ?? block.line) + start
      })
    } catch { /* This block cannot supply compiled evidence. */ }
  }
  const headings = lines.flatMap((line, i) => /^#{1,6}\s/.test(line) ? [i + 1] : [])
  const lower = Math.max(0, ...headings.filter(n => n <= rule.line))
  const upper = headings.find(n => n > rule.line) ?? lines.length + 1
  const nearby = blocks.filter(b => b.line > lower && b.line < upper && Math.abs(b.line - rule.line) <= 40)
  return nearby.flatMap((vibe, i) => {
    const effect = nearby[i + 1]
    if (vibe.language !== "vibe" || effect?.language !== "ts" || !effect.comparison) return []
    if ([vibe, effect].some(b => b.fragment || b.gap || b.pending || b.expected.length)) return []
    return exercises(rule, vibe.source) ? [{ vibe, effect }] : []
  })
}

export async function checkEntry(entry: Entry, checkTwin: (t: Twin) => Promise<TwinResult> = compileTwin) {
  const rules = changedRules(entry.changes), findings: Finding[] = []
  let cases = 0, twins = 0, pending = 0
  const compiled = new Map<string, TwinResult>()
  for (const rule of rules) {
    const markdown = entry.changes.find(c => c.path === rule.path)![rule.removed ? "before" : "after"]
    const ownKeys = anchors(rule.text)
    const strong = ownKeys.some(k => keywords.has(k) || k.includes(".") || /^(?:(?:EK|TS)\d|@|__|!!|=>|\|>)/.test(k))
    const subject = !strong ? sentences(rule.path, markdown).filter(s =>
      s.section === rule.section && s.line <= rule.line && rule.line - s.line <= 40 && s.text !== rule.text && anchors(s.text).length
    ).at(-1) : undefined
    if (caseEvidence(rule, entry.changes) || (subject && caseEvidence(subject, entry.changes))) { cases++; continue }
    const pairs = nearbyTwins(rule, markdown)
    let last = "no adjacent complete `vibe` / `ts effect` pair"
    let proved = false
    for (const pair of pairs) {
      const key = JSON.stringify(pair)
      const result = compiled.get(key) ?? await checkTwin(pair)
      compiled.set(key, result)
      if (result.ok) { proved = true; twins++; break }
      last = result.reason
    }
    if (!proved && pendingEvidence(rule, entry.changes)) { pending++; continue }
    if (!proved) findings.push({ ...rule, missing: "missing a changed compiler case exercising this rule, a compiled Effect twin with identical nonempty .d.ts or Exit, or an exact changed pending test; " + last })
  }
  return { base: entry.base, head: entry.head, rules: rules.length, cases, twins, pending, findings }
}

// Use the snippet checker's extraction and dependency isolation. Both sources
// are checked as separate, strict modules, with no inherited prose fixtures.
// Declarations compare byte-for-byte; the explicit Exit path compares real
// runtime values. No type/import normalization can hide an API difference. Require a real API, not two empty export {} modules.
export async function compileTwin(twin: Twin, compiler = defaultCompiler()): Promise<TwinResult> {
  const witness = (block: Block) => block.source.match(/^\s*\/\/ rule-evidence-exit: (\S+)\s*$/m)?.[1]
  const vibeExit = witness(twin.vibe), effectExit = witness(twin.effect)
  if ((vibeExit || effectExit) && (vibeExit !== effectExit || !/^[A-Za-z_$][\w$]*$/.test(vibeExit!))) {
    return { ok: false, reason: "both twins must name the same exported Effect in // rule-evidence-exit: name" }
  }
  const temp = mkdtempSync(join(process.env.RULE_EVIDENCE_TMPDIR || tmpdir(), "vibelang-rule-evidence-"))
  try {
    linkModules(temp)
    const declarations: string[] = []
    for (const [name, block] of [["vibe", twin.vibe], ["effect", twin.effect]] as const) {
      const dir = join(temp, name)
      mkdirSync(dir)
      const file = "main." + block.language
      writeFileSync(join(dir, file), block.source)
      writeFileSync(join(dir, "package.json"), '{"type":"module"}')
      writeFileSync(join(dir, "tsconfig.json"), JSON.stringify({ compilerOptions: {
        strict: true, target: "ESNext", module: "NodeNext", moduleResolution: "NodeNext",
        skipLibCheck: true, types: block.types ?? [], declaration: true, emitDeclarationOnly: !vibeExit, outDir: "out"
      }, files: [file] }))
      const result = await command([resolve(compiler), "--project", "tsconfig.json", "--pretty", "false"], dir, 30_000)
      if (result.exitCode !== 0 || result.timedOut) return { ok: false, reason: name + " twin " + (result.timedOut ? "timed out" : "did not compile") + ": " + (result.stdout + result.stderr).slice(0, 2000) }
      const declaration = join(dir, "out/main.d.ts")
      if (!existsSync(declaration)) return { ok: false, reason: name + " twin emitted no main.d.ts" }
      const text = readFileSync(declaration, "utf8")
      if (!/\bexport\b/.test(text) || !text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/export\s*\{\s*\}\s*;?/g, "").trim()) {
        return { ok: false, reason: name + " twin has an empty API; export the rule witness" }
      }
      declarations.push(text)
    }
    if (vibeExit) {
      writeFileSync(join(temp, "compare.mjs"), `
import { Effect } from "effect"
import { isDeepStrictEqual } from "node:util"
import * as vibe from "./vibe/out/main.js"
import * as twin from "./effect/out/main.js"
const name = ${JSON.stringify(vibeExit)}
if (!Effect.isEffect(vibe[name]) || !Effect.isEffect(twin[name])) throw new Error("Exit witness must export an Effect")
const a = await Effect.runPromise(Effect.exit(vibe[name]))
const b = await Effect.runPromise(Effect.exit(twin[name]))
if (!isDeepStrictEqual(a, b)) { console.error("twin Exit differs"); process.exitCode = 1 }
`)
      const result = await command(["node", "compare.mjs"], temp, 30_000)
      return { ok: result.exitCode === 0 && !result.timedOut, reason: result.timedOut ? "Exit comparison timed out" :
        result.exitCode === 0 ? "identical Exit" : "Exit comparison failed: " + (result.stdout + result.stderr).slice(0, 2000) }
    }
    return { ok: declarations[0] === declarations[1], reason: declarations[0] === declarations[1] ? "identical .d.ts" : "twin .d.ts differs" }
  } finally { rmSync(temp, { recursive: true, force: true }) }
}

function jj(root: string, args: string[]): string {
  const result = spawnSync("jj", ["--ignore-working-copy", "--color=never", ...args], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  if (result.status !== 0) throw new Error("jj " + args[0] + " failed: " + (result.stderr || result.error?.message))
  return result.stdout
}
// Request full context once rather than spawning jj per file. Effect pin
// entries can change thousands of manifests; per-file reads took minutes.
export function parseDiff(patch: string): Change[] {
  const changes: Change[] = []
  let oldPath = "", newPath = "", old: string[] = [], next: string[] = []
  let hunk = false, previous = "", oldNoNewline = false, newNoNewline = false
  const decode = (path: string) => path.startsWith('"') ? JSON.parse(path) as string : path
  const flush = () => {
    if (!hunk) return
    const before = old.join("\n") + (old.length && !oldNoNewline ? "\n" : "")
    const after = next.join("\n") + (next.length && !newNoNewline ? "\n" : "")
    if (oldPath === newPath) changes.push({ path: oldPath, before, after })
    else {
      if (oldPath) changes.push({ path: oldPath, before, after: "" })
      if (newPath) changes.push({ path: newPath, before: "", after })
    }
  }
  for (const line of patch.split("\n")) {
    if (line.startsWith("diff --git ")) {
      flush(); oldPath = ""; newPath = ""; old = []; next = []
      hunk = false; oldNoNewline = false; newNoNewline = false; previous = ""
    } else if (!hunk && line.startsWith("--- ")) {
      const path = decode(line.slice(4)); oldPath = path === "/dev/null" ? "" : path.slice(2)
    } else if (!hunk && line.startsWith("+++ ")) {
      const path = decode(line.slice(4)); newPath = path === "/dev/null" ? "" : path.slice(2)
    } else if (line.startsWith("@@ ")) {
      if (hunk || !/^@@ -(?:0|1)(?:,\d+)? \+(?:0|1)(?:,\d+)? @@/.test(line)) throw new Error("incomplete full-context jj diff")
      hunk = true
    } else if (hunk) {
      const sign = line[0]
      if (sign === " " || sign === "-") old.push(line.slice(1))
      if (sign === " " || sign === "+") next.push(line.slice(1))
      if (line.startsWith("\\ No newline")) {
        if (previous !== "+") oldNoNewline = true
        if (previous !== "-") newNoNewline = true
      } else previous = sign
    }
  }
  flush()
  return changes.filter(c => specPath(c.path) || casePath(c.path) || pendingPath(c.path))
}

export function collectEntry(root: string, base: string, head: string): Entry {
  const revision = (r: string) => {
    const id = jj(root, ["log", "--no-graph", "-r", r, "-T", 'commit_id ++ "\n"']).trim()
    if (!/^[0-9a-f]{40,64}$/.test(id)) throw new Error("revision must resolve to exactly one commit: " + r)
    return id
  }
  base = revision(base); head = revision(head)
  const patch = jj(root, ["diff", "--from", base, "--to", head, "--git", "--context", "1000000", "--",
    "docs/design/src", "docs/design/vips", "typescript/vibelang/cases", "docs/tools"])
  const changes = parseDiff(patch)

  return { base, head, changes }
}

async function main() {
  const args = process.argv.slice(2)
  if (args.includes("--help")) {
    console.log("bun docs/tools/rule-evidence.ts --base <revision> --head <revision> [--json <path>] [--immutable]\nSmithers: RULE_EVIDENCE_BASE=<commit> RULE_EVIDENCE_HEAD=<commit> smthrs test //:spec-rule-evidence\nExit 0: evidenced/exempt; 1: missing evidence; 2: setup/revision/compiler failure.")
    return
  }
  const option = (name: string, fallback?: string) => {
    const i = args.indexOf(name)
    if (i < 0) return fallback
    const value = args[i + 1]
    if (!value || value.startsWith("--")) throw new Error(name + " requires a value")
    args.splice(i, 2)
    return value
  }
  const base = option("--base", process.env.RULE_EVIDENCE_BASE), head = option("--head", process.env.RULE_EVIDENCE_HEAD)
  const json = option("--json")
  const immutable = args.includes("--immutable")
  if (immutable) args.splice(args.indexOf("--immutable"), 1)
  if (immutable && (![base, head].every(r => r && /^[0-9a-f]{40,64}$/.test(r)))) throw new Error("Smithers requires full immutable base/head commit IDs; resolve revision names with jj log first")
  if (args.length || !base || !head) throw new Error("supply --base and --head (or RULE_EVIDENCE_BASE/HEAD); unknown arguments: " + args.join(" "))
  const result = await checkEntry(collectEntry(repo, base, head))
  if (json) writeFileSync(json, JSON.stringify(result, null, 2) + "\n")
  for (const finding of result.findings) console.error(finding.path + ":" + finding.line + ': "' + finding.text + '"\n  ' + finding.missing)
  console.log("spec-rule-evidence: " + result.rules + " changed normative sentences; " + result.cases + " cases; " + result.twins + " compiled twins; " + result.pending + " pending tests; " + result.findings.length + " missing")
  process.exitCode = result.findings.length ? 1 : 0
}
if (import.meta.main) main().catch(error => { console.error("spec-rule-evidence: " + error.message); process.exitCode = 2 })
