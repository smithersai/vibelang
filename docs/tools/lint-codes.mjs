import { createHash } from "node:crypto"
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve, relative } from "node:path"
import { fileURLToPath } from "node:url"

export const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
const upstream = "typescript/tsc/internal/effecttsgo"
const rulesDir = upstream + "/internal/rules"
const assignmentsPath = "docs/tools/lint-code-assignments.json"
export const artifactPath = "docs/design/inventory/lint-codes.json"
const pages = ["docs/design/src/007-tooling.md", "docs/design/src/900-appendices.md"]
const read = path => readFileSync(resolve(root, path), "utf8")
const digest = text => createHash("sha256").update(text).digest("hex")
export const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0

export function assignCodes(names, previous = {}) {
  if (previous.floatingEffect && previous.floatingEffect !== "EK3801")
    throw new Error("floatingEffect must retain EK3801 (decided detail 106)")
  const assigned = { floatingEffect: "EK3801", ...previous }
  const used = new Set(Object.values(assigned))
  if (used.size !== Object.keys(assigned).length ||
      [...used].some(code => !/^EK38[0-9]{2,}$/.test(code))) {
    throw new Error("Invalid or duplicate lint code assignments")
  }
  let next = Math.max(0, ...[...used].map(code => Number(code.slice(4)))) + 1
  for (const name of [...names].sort(compare)) {
    if (!assigned[name]) assigned[name] = "EK38" + String(next++).padStart(2, "0")
  }
  return assigned
}

export function generateLintCodes() {
  const inputs = []
  function input(path) {
    const source = read(path)
    inputs.push({ file: path, sha256: digest(source) })
    return source
  }
  const pin = Object.fromEntries([...input(upstream + "/UPSTREAM")
    .matchAll(/^(repository|tag|commit): (.+)$/gm)].map(m => [m[1], m[2]]))
  if (!pin.tag || !pin.commit) throw new Error("Missing Effect tsgo upstream pin")
  const registry = input(rulesDir + "/rules.go")
  const active = registry.match(/var All = \[\]rule.Rule\{([\s\S]*?)\n\}/)?.[1]
  if (!active) throw new Error("Cannot read the upstream rule registry")
  const symbols = [...active.matchAll(/^\s*(\w+),\s*$/gm)].map(m => m[1])
  const definitions = new Map()
  for (const file of readdirSync(resolve(root, rulesDir)).filter(f => f.endsWith(".go") && !f.endsWith("_test.go")).sort(compare)) {
    if (file === "rules.go") continue
    const source = read(rulesDir + "/" + file)
    let used = false
    for (const m of source.matchAll(/var (\w+) = rule.Rule\{\s*Name:\s*"([^"]+)"[\s\S]*?DefaultSeverity:\s*etscore.Severity(\w+)/g)) {
      if (!symbols.includes(m[1])) continue
      definitions.set(m[1], { rule: m[2], defaultSeverity: m[3].toLowerCase(), source: rulesDir + "/" + file })
      used = true
    }
    if (used) input(rulesDir + "/" + file)
  }
  const rules = symbols.map(symbol => {
    if (!definitions.has(symbol)) throw new Error("Unparsed registered rule: " + symbol)
    return definitions.get(symbol)
  }).sort((a, b) => compare(a.rule, b.rule))
  if (new Set(rules.map(r => r.rule)).size !== rules.length) throw new Error("Duplicate upstream rule name")
  const previous = existsSync(resolve(root, assignmentsPath)) ? JSON.parse(read(assignmentsPath)) : {}
  const assignments = assignCodes(rules.map(r => r.rule), previous)
  const inventory = {
    schemaVersion: 1,
    generatedBy: "node docs/tools/lint-codes.mjs --write",
    upstream: pin,
    allocation: "EK38 plus a decimal ordinal of at least two digits (EK3801 through EK3899, then EK38100). Retain EK3801 for floatingEffect; sort all other initial rules by name from ordinal 2 (detail 106). Future new names are sorted and appended after the largest reserved ordinal; removed names remain reserved in docs/tools/lint-code-assignments.json. Never renumber or reuse a code.",
    inputs: inputs.sort((a, b) => compare(a.file, b.file)),
    rules: rules.map(rule => ({ code: assignments[rule.rule], ...rule })),
  }
  return { inventory, assignments }
}

export function renderLintTable(inventory) {
  return [
    "<!-- lint-codes:start: generated by docs/tools/lint-codes.mjs; do not edit -->",
    "",
    "Imported rules from `" + inventory.upstream.tag + "` (commit `" + inventory.upstream.commit + "`).",
    "",
    "| Code | Rule | VIP | Chapter | Default severity |",
    "| --- | --- | --- | --- | --- |",
    ...inventory.rules.map(r => "| `" + r.code + "` | `effecttsgo/" + r.rule + "` | 38 | [Tooling](007-tooling.md) | `" + r.defaultSeverity + "` |"),
    "",
    "<!-- lint-codes:end -->",
  ].join("\n")
}

export function lintOutputs() {
  const { inventory, assignments } = generateLintCodes()
  const outputs = new Map([
    [artifactPath, JSON.stringify(inventory, null, 2) + "\n"],
    [assignmentsPath, JSON.stringify(assignments, null, 2) + "\n"],
  ])
  for (const page of pages) {
    const source = read(page)
    const pattern = /<!-- lint-codes:start[^\n]*-->[\s\S]*?<!-- lint-codes:end -->/
    if (!pattern.test(source)) throw new Error("Missing lint table markers in " + page)
    outputs.set(page, source.replace(pattern, () => renderLintTable(inventory)))
  }
  return outputs
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes("--write")
  let stale = false
  for (const [path, expected] of lintOutputs()) {
    if (existsSync(resolve(root, path)) && read(path) === expected) continue
    if (write) {
      mkdirSync(dirname(resolve(root, path)), { recursive: true })
      writeFileSync(resolve(root, path), expected)
    } else {
      console.error("Stale or missing " + path + "; run node docs/tools/lint-codes.mjs --write")
      stale = true
    }
  }
  process.exitCode = stale ? 1 : 0
}
