import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"
import { command, defaultCompiler, extract, linkModules, type Block } from "./check-snippets"
export type Twin = { vibe: Block; effect: Block }
export type TwinResult = { ok: boolean; reason: string }
// Normative sentence API extracted verbatim from gate-rule-evidence dd4ff590c915.
// Portable fallback until rule-evidence.ts lands; the census prefers that module.
export type Sentence = { path: string; line: number; text: string; section: string; removed?: boolean }
const generated = (text: string) => /^\s*<!--[^>]*(?:generated by|automatically generated|auto-generated|do not edit)[^>]*-->/i.test(text)
const slug = (text: string) => text.toLowerCase().replace(/\x60/g, "").replace(/[^\p{L}\p{N}_ -]/gu, "").trim().replace(/\s+/g, "-")
export function canonical(text: string): string {
  const parts = text.split(/(`+[^`]*`+)/g)
  const cited = parts.map((part, i) => i % 2
    ? /\beffect\s+$/i.test(parts[i - 1]) && /^(`+)\d+\.\d+\.\d+\1$/.test(part) ? "<version>" : part
    : part.replace(/\b(effect\s+)\d+\.\d+\.\d+/gi, "$1<version>")).join("")
  return cited
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\s*\((?:(?:decided )?details? \d+[a-z]?(?:[ ,and–-]+\d+[a-z]?)*|VIP-\d+(?:, amended)?)\)/gi, "").split(/(`+[^`]*`+)/g).map((part, i) =>
    i % 2 ? part : part.replace(/[*_]/g, "").replace(/\b(teh|thier|occurrs|recieve|sentance)\b/gi, word =>
      ({ teh: "the", thier: "their", occurrs: "occurs", recieve: "receive", sentance: "sentence" })[word.toLowerCase()]!).toLowerCase()
  ).join("").replace(/\s+/g, " ").replace(/[.!?]+$/, "").trim()
}

export function sentences(path: string, markdown: string): Sentence[] {
  if (generated(markdown)) return []
  const out: Sentence[] = []
  const lines = markdown.split(/\r?\n/)
  let fence = "", section = "", paragraph: { text: string; line: number }[] = [], comment = false
  const flush = () => {
    if (!paragraph.length) return
    const joined = paragraph.map(p => p.text).join("\n")
    // Split outside inline code. Dots inside a code span, e.g. `Effect.fail`,
    // and source line wrapping do not create sentences.
    let start = 0, ticks = 0
    for (let i = 0; i <= joined.length; i++) {
      if (joined[i] === "`") {
        let n = 1
        while (joined[i + n] === "`") n++
        ticks = ticks === n ? 0 : ticks || n
        i += n - 1
      }
      if (i === joined.length || (!ticks && /[.!?]/.test(joined[i]) && /\s/.test(joined[i + 1] ?? ""))) {
        const end = i === joined.length ? i : i + 1
        const part = joined.slice(start, end)
        const textStart = start + Math.max(0, part.search(/\S/))
        if (part.trim()) out.push({ path, line: paragraph[0].line + joined.slice(0, textStart).split("\n").length - 1,
          text: part.trim().replace(/\s+/g, " "), section })
        start = end
      }
    }
    paragraph = []
  }
  for (const [i, raw] of lines.entries()) {
    let original = raw
    const f = /^\s{0,3}(`{3,}|~{3,})/.exec(original)
    if (fence) {
      if (new RegExp("^\\s{0,3}" + fence[0] + "{" + fence.length + ",}\\s*$").test(original)) fence = ""
      continue
    }
    if (comment) {
      const close = original.indexOf("-->")
      if (close < 0) continue
      original = original.slice(close + 3); comment = false
    }
    while (original.includes("<!--")) {
      const start = original.indexOf("<!--"), end = original.indexOf("-->", start + 4)
      if (end < 0) { original = original.slice(0, start); comment = true; break }
      original = original.slice(0, start) + original.slice(end + 3)
    }
    if (f && original === raw) { flush(); fence = f[1]; continue }
    const heading = /^#{1,6}\s+(.+)$/.exec(original)
    if (heading) { flush(); section = slug(heading[1]); continue }
    if (!original.trim() || /^\s*(?:\[[^\]]+\]:|---+$|\|?\s*:?-+:?\s*\|)/.test(original)) { flush(); continue }
    // Lists and table rows are independent rules rather than one huge paragraph.
    if (/^\s*(?:[-*+] |\d+\. |\|)/.test(original)) flush()
    paragraph.push({ text: original.replace(/^\s*(?:[-*+] |\d+\. )/, ""), line: i + 1 })
    if (/^\s*\|/.test(original)) flush()
  }
  flush()
  return out
}

export function normative(text: string): boolean {
  if (/^`EK\d+` to `EK\d+` keep their specific triggers\.$/.test(text)) return false
  return /`[^`]+`|\b(?:EK|TS)\d{4,}\b|\b(?:must|compiles?|means)\b|\bis an? error\b/i.test(text)
}

export function anchors(text: string): string[] {
  const codes = [...text.matchAll(/\b(?:EK|TS)\d{4,}\b/g)].map(m => m[0])
  if (codes.length) return [...new Set(codes)]
  const spans = [...text.matchAll(/`+([^`]+)`+/g)].map(m => m[1])
  const words = spans.flatMap(s => s.match(/[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*/g) ?? [])
  const grammar: Record<string, string> = { CatchExpression: "catch", ArrowHandler: "=>", PipeExpression: "|>",
    PipeBody: "|>", EffectArrow: "effect", MatchExpression: "match", MatchPattern: "when", VariableStatement: "var",
    ProvideStatement: "provide", ErrorDeclaration: "error", ServiceDeclaration: "service", SchemaDeclaration: "schema" }
  const aliases: Record<string, string> = { "Context.Service": "service", "Context.Reference": "service",
    "Data.TaggedError": "error", "Schema.TaggedError": "error", "Schema.Struct": "schema" }
  const specific = words.filter(w => w.length > 1).flatMap(w =>
    Object.hasOwn(grammar, w) ? [grammar[w]] :
      [w, ...(w.includes(".") ? [w.split(".").at(-1)!] : []), ...(Object.hasOwn(aliases, w) ? [aliases[w]] : [])])
  const operators = spans.flatMap(s => s.match(/!!|=>|\|>/g) ?? [])
  return [...new Set([...specific, ...operators])]
}

function exercises(rule: Sentence, body: string): boolean {
  const keys = anchors(rule.text)
  return keys.length > 0 && keys.some(key => {
    if (key === "for") return /\bfor\s*\([^)]*\bof\b/.test(body)
    return body.includes(key)
  })
}
export function nearbyTwins(rule: Sentence, markdown: string): Twin[] {
  if (rule.removed) return []
  const lines = markdown.split(/\r?\n/)
  const blocks: Block[] = []
  // Old VIPs contain mislabeled examples. An invalid unrelated fence cannot
  // turn an entry's missing-evidence verdict into a setup failure.
  for (let i = 0; i < lines.length; i++) {
    const fence = /^\s{0,3}(`{3,}|~{3,})/.exec(lines[i])
    if (!fence) continue
    const start = i
    const close = new RegExp("^\\s{0,3}" + fence[1][0] + "{" + fence[1].length + ",}\\s*$")
    while (++i < lines.length && !close.test(lines[i])) {}
    try {
      for (const block of extract(lines.slice(start, i + 1).join("\n"))) blocks.push({
        ...block, number: blocks.length + 1, line: block.line + start, endLine: (block.endLine ?? block.line) + start
      })
    } catch { /* This block cannot supply compiled evidence. */ }
  }
  const headings = lines.flatMap((line, i) => /^#{1,6}\s/.test(line) ? [i + 1] : [])
  const lower = Math.max(0, ...headings.filter(n => n <= rule.line))
  const upper = headings.find(n => n > rule.line) ?? lines.length + 1
  const nearby = blocks.filter(b => b.line > lower && b.line < upper && Math.abs(b.line - rule.line) <= 40)
  return nearby.flatMap((vibe, i) => {
    const effect = nearby[i + 1]
    if (vibe.language !== "vibe" || effect?.language !== "ts" || !effect.comparison) return []
    if ([vibe, effect].some(b => b.fragment || b.gap || b.pending || b.expected.length)) return []
    return exercises(rule, vibe.source) ? [{ vibe, effect }] : []
  })
}

export async function compileTwin(twin: Twin, compiler = defaultCompiler()): Promise<TwinResult> {
  const witness = (block: Block) => block.source.match(/^\s*\/\/ rule-evidence-exit: (\S+)\s*$/m)?.[1]
  const vibeExit = witness(twin.vibe), effectExit = witness(twin.effect)
  if ((vibeExit || effectExit) && (vibeExit !== effectExit || !/^[A-Za-z_$][\w$]*$/.test(vibeExit!))) {
    return { ok: false, reason: "both twins must name the same exported Effect in // rule-evidence-exit: name" }
  }
  const temp = mkdtempSync(join(process.env.RULE_EVIDENCE_TMPDIR || tmpdir(), "vibelang-rule-evidence-"))
  try {
    linkModules(temp)
    const declarations: string[] = []
    for (const [name, block] of [["vibe", twin.vibe], ["effect", twin.effect]] as const) {
      const dir = join(temp, name)
      mkdirSync(dir)
      const file = "main." + block.language
      writeFileSync(join(dir, file), block.source)
      writeFileSync(join(dir, "package.json"), '{"type":"module"}')
      writeFileSync(join(dir, "tsconfig.json"), JSON.stringify({ compilerOptions: {
        strict: true, target: "ESNext", module: "NodeNext", moduleResolution: "NodeNext",
        skipLibCheck: true, types: block.types ?? [], declaration: true, emitDeclarationOnly: !vibeExit, outDir: "out"
      }, files: [file] }))
      const result = await command([resolve(compiler), "--project", "tsconfig.json", "--pretty", "false"], dir, 30_000)
      if (result.exitCode !== 0 || result.timedOut) return { ok: false, reason: name + " twin " + (result.timedOut ? "timed out" : "did not compile") + ": " + (result.stdout + result.stderr).slice(0, 2000) }
      const declaration = join(dir, "out/main.d.ts")
      if (!existsSync(declaration)) return { ok: false, reason: name + " twin emitted no main.d.ts" }
      const text = readFileSync(declaration, "utf8")
      if (!/\bexport\b/.test(text) || !text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/export\s*\{\s*\}\s*;?/g, "").trim()) {
        return { ok: false, reason: name + " twin has an empty API; export the rule witness" }
      }
      declarations.push(text)
    }
    if (vibeExit) {
      writeFileSync(join(temp, "compare.mjs"), `
import { Effect } from "effect"
import { isDeepStrictEqual } from "node:util"
import * as vibe from "./vibe/out/main.js"
import * as twin from "./effect/out/main.js"
const name = ${JSON.stringify(vibeExit)}
if (!Effect.isEffect(vibe[name]) || !Effect.isEffect(twin[name])) throw new Error("Exit witness must export an Effect")
const a = await Effect.runPromise(Effect.exit(vibe[name]))
const b = await Effect.runPromise(Effect.exit(twin[name]))
if (!isDeepStrictEqual(a, b)) { console.error("twin Exit differs"); process.exitCode = 1 }
`)
      const result = await command(["node", "compare.mjs"], temp, 30_000)
      return { ok: result.exitCode === 0 && !result.timedOut, reason: result.timedOut ? "Exit comparison timed out" :
        result.exitCode === 0 ? "identical Exit" : "Exit comparison failed: " + (result.stdout + result.stderr).slice(0, 2000) }
    }
    return { ok: declarations[0] === declarations[1], reason: declarations[0] === declarations[1] ? "identical .d.ts" : "twin .d.ts differs" }
  } finally { rmSync(temp, { recursive: true, force: true }) }
}

