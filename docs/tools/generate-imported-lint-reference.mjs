import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../..", import.meta.url))
const target = "docs/user/src/vibelang-features/imported-lint-diagnostics.md"
const read = file => readFileSync(resolve(root, file), "utf8")
const cell = text => text.replaceAll("|", "\\|").replace(/\s*\n\s*/g, " ").trim()

export function renderImportedLintReference(inventory, messages) {
  const byRule = new Map()
  for (const message of Object.keys(messages)) {
    const match = / effect\((\w+)\)$/.exec(message)
    if (!match) continue
    if (!byRule.has(match[1])) byRule.set(match[1], [])
    byRule.get(match[1]).push(message.slice(0, match.index))
  }
  const rows = inventory.rules.map(rule => {
    const templates = byRule.get(rule.rule)
    if (!templates?.length) throw new Error(rule.code + ": no upstream diagnostic message for " + rule.rule)
    const source = rule.source.replace("typescript/tsc/internal/effecttsgo/", "")
    const link = inventory.upstream.repository + "/blob/" + inventory.upstream.commit + "/" + source
    return "| `" + rule.code + "` | [`effecttsgo/" + rule.rule + "`](" + link + ") | `" + rule.defaultSeverity + "` | " +
      templates.map(cell).join("<br /><br />") + " |"
  })
  return [
    "<!-- Generated by docs/tools/generate-imported-lint-reference.mjs; edit the generator or pinned upstream sources, then run it with --write. -->",
    "# Imported lint diagnostics", "",
    "These are the imported `effecttsgo/*` rules from `" + inventory.upstream.tag + "`. The code identifies the rule; a rule can have several messages. Placeholders such as `{0}` are replaced by the names and types from your source.", "",
    "Follow the message's advice at the reported source location, change the source manually and rerun the original check. VibeLang does not provide automatic fixes for these diagnostics.", "",
    "The default column comes from the pinned rule. Suggestions appear in the language server and can print in compiler checks when `includeSuggestionsInTsc` is `true`. A rule whose default is `off` must be enabled to report. File and Effect-version eligibility still apply. Configure supported rules with [`vibe.severities`](../setup/vibelang-cli.md#diagnostic-severities); the full code matters: `EK3810` and `EK38100` are different rules.", "",
    "Each rule name links to its pinned implementation. The table quotes its diagnostic messages so that a terminal or editor message can be found verbatim.", "",
    "| Code | Rule | Default | Messages and repair advice |",
    "| --- | --- | --- | --- |",
    ...rows, ""
  ].join("\n")
}

export function importedLintReference() {
  return renderImportedLintReference(
    JSON.parse(read("docs/design/inventory/lint-codes.json")),
    JSON.parse(read("typescript/tsc/internal/effecttsgo/internal/diagnostics/effectDiagnosticMessages.json"))
  )
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = importedLintReference()
  if (process.argv.includes("--write")) writeFileSync(resolve(root, target), expected)
  else if (read(target) !== expected) {
    console.error("Stale " + target + "; run node docs/tools/generate-imported-lint-reference.mjs --write")
    process.exitCode = 1
  }
}
